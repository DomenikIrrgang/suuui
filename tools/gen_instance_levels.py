# tools/gen_instance_levels.py
# Writes src/Data/InstanceLevels.wowlua: the recommended levels of Forever's
# dungeons, raids and battlegrounds, by the names of their entrances on the
# map (Data/QuestStarts.wowlua). From Forever's client table (DB2)
# GroupFinderActivity, from wago.tools: its MinLevel and MaxLevelSuggestion,
# the range the game's group finder shows.
#   sh tools/update_instance_levels.sh
#   (or: python3 -I tools/gen_instance_levels.py <dir with the CSV> <build> src/Data/InstanceLevels.wowlua)
import csv, sys, os, re, collections
DIR, BUILD, OUT = sys.argv[1:4]

# the group finder's categories, as the entrances' kinds
KIND = {'2': 'dungeon', '114': 'raid', '118': 'battleground'}
# Season of Discovery's activities, still in the client but not in Forever:
# its raid versions of dungeons (Blackfathom Deeps, Gnomeregan, Sunken
# Temple), its own places (Demon Fall Canyon, Storm Cliffs, The Tainted
# Scar, Nightmare Grove, The Crystal Vale, Karazhan Crypts, Scarlet Enclave)
# and its versions of the old raids (Onyxia's Lair, Molten Core, Ahn'Qiraj)
SOD = set(range(1604, 1616)) | {1693, 1710}
# group finder names that aren't the entrance's
RENAME = {
    'Deadmines': 'The Deadmines',
    'Stormwind Stockades': 'The Stockade',
    'Sunken Temple': "The Temple of Atal'Hakkar",
    'Hall of Thanes': 'The Hall of Thanes',
    "Ahn'Qiraj Ruins": "Ruins of Ahn'Qiraj",
    "Ahn'Qiraj Temple": "Temple of Ahn'Qiraj",
}
# a wing: "Scarlet Monastery - Library", "Dire Maul (East)", "Lower Blackrock Spire"
def split(name):
    m = re.match(r'^(.*) - (.*)$', name) or re.match(r'^(.*) \((.*)\)$', name)
    if m: return m.group(1), m.group(2)
    m = re.match(r'^(Lower|Upper) (.*)$', name)
    if m: return m.group(2), m.group(1)
    return name, None

places = collections.OrderedDict()   # (kind, name) -> {wing or None: [min, max]}
for r in csv.DictReader(open(os.path.join(DIR, 'GroupFinderActivity.csv'), encoding='utf-8')):
    kind = KIND.get(r['GroupFinderCategoryID'])
    lo, hi = int(r['MinLevel']), int(r['MaxLevelSuggestion'])
    if not kind or lo <= 0 or int(r['ID']) in SOD: continue
    name, wing = split(r['FullName_lang'])
    name = RENAME.get(name, name)
    ranges = places.setdefault((kind, name), {})
    # a battleground's brackets make one range
    old = ranges.get(wing)
    ranges[wing] = [min(old[0], lo), max(old[1], hi)] if old else [lo, hi]

def lua(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
out = []
w = out.append
w('-- Data/InstanceLevels.wowlua (generated by tools/gen_instance_levels.py: do not edit)')
w("-- The recommended levels of Forever's dungeons, raids and battlegrounds (the group finder's).")
w("--   Forever's client table GroupFinderActivity, build %s (wago.tools)" % BUILD)
w('--   rebuild: sh tools/update_instance_levels.sh')
w('--   [kind][entrance name] = { min, max, { wing, min, max }, ... }  (kind "dungeon", "raid", "battleground";')
w('--   min, max over the wings; a battleground over its brackets)')
w('')
w('--- { min, max, { wing, min, max }, ... }: numbers, then a list per wing')
w('export type InstanceLevel = any[]')
w('export type InstanceLevels = { [string]: { [string]: InstanceLevel } }')
w('')
w('export local instanceLevels: InstanceLevels = {')
for kind in ('dungeon', 'raid', 'battleground'):
    w('    %s = {' % kind)
    for (k, name), ranges in sorted(places.items(), key=lambda kv: kv[0][1]):
        if k != kind: continue
        lo = min(v[0] for v in ranges.values()); hi = max(v[1] for v in ranges.values())
        wings = sorted(((wg, v) for wg, v in ranges.items() if wg), key=lambda x: (x[1][0], x[1][1], x[0]))
        parts = ['%d, %d' % (lo, hi)] + ['{ %s, %d, %d }' % (lua(wg), v[0], v[1]) for wg, v in wings]
        w('        [%s] = { %s },' % (lua(name), ', '.join(parts)))
    w('    },')
w('}')
open(OUT, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('wrote %s: %d places' % (OUT, len(places)))
