# tools/gen_map_overlays.py
# Writes src/Data/MapOverlays.lua: every area overlay of Forever's maps (the
# pieces the map shows once you've explored an area), so the world map can
# draw the ones you haven't explored too. From Forever's client tables
# (DB2) WorldMapOverlay and WorldMapOverlayTile, from wago.tools.
#   sh tools/update_map_overlays.sh
#   (or: python3 -I tools/gen_map_overlays.py <dir with the CSVs> <build> src/Data/MapOverlays.lua)
import csv, sys, os, collections
DIR, BUILD, OUT = sys.argv[1:4]
def rows(t): return csv.DictReader(open(os.path.join(DIR, t + '.csv'), encoding='utf-8'))

tiles = collections.defaultdict(list)   # overlay -> [(row, col, fileDataID)] (the base layer's)
for r in rows('WorldMapOverlayTile'):
    if r['LayerIndex'] == '0':
        tiles[r['WorldMapOverlayID']].append((int(r['RowIndex']), int(r['ColIndex']), int(r['FileDataID'])))

byArt = collections.defaultdict(list)
skipped = 0
for r in rows('WorldMapOverlay'):
    # an overlay shown only under a condition (a phase, a quest) is left out
    if r['PlayerConditionID'] != '0' or not tiles[r['ID']]:
        skipped += 1
        continue
    files = [f for _, _, f in sorted(tiles[r['ID']])]
    byArt[int(r['UiMapArtID'])].append((int(r['TextureWidth']), int(r['TextureHeight']), int(r['OffsetX']), int(r['OffsetY']), files))

o = []
o.append('-- Data/MapOverlays.lua (generated by tools/gen_map_overlays.py: do not edit)')
o.append('-- Every area overlay of Forever\'s maps, for drawing the areas you haven\'t explored.')
o.append('--   Forever\'s client tables WorldMapOverlay and WorldMapOverlayTile, build %s (wago.tools)' % BUILD)
o.append('--   rebuild: sh tools/update_map_overlays.sh')
o.append('--   [uiMapArtID] = { { textureWidth, textureHeight, offsetX, offsetY, fileDataID, ... (row by row) }, ... }')
o.append('')
o.append('local _, ns = ...')
o.append('')
o.append('ns.MapOverlays = {')
total = 0
for art in sorted(byArt):
    cells = []
    for w, h, x, y, files in sorted(byArt[art], key=lambda e: (e[3], e[2])):
        cells.append('{%d,%d,%d,%d,%s}' % (w, h, x, y, ','.join(map(str, files))))
        total += 1
    o.append('    [%d] = {%s},' % (art, ','.join(cells)))
o.append('}')
o.append('')
open(OUT, 'w', encoding='utf-8').write('\n'.join(o))
print('gen_map_overlays: %d overlays on %d maps (%d left out) -> %s' % (total, len(byArt), skipped, OUT))
