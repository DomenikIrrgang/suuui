-- tools/gen_defensives.lua
-- Generates src/Data/Defensives.lua: SuuUI's default list of defensives for
-- party and raid frames, each name turned into every spell ID that carries
-- exactly that name in the client (the Forever spell scans). A name the
-- client doesn't have stops the run.
--   lua tools/gen_defensives.lua            (from the repository root)

local SCANS = { "tools/data/forever_spells.tsv", "tools/data/forever_own.tsv", "tools/data/found.tsv" }
local OUT = "src/Data/Defensives.lua"

-- { name, kind, warded, note }: kind "external" (someone else puts it on
-- you) or "defensive" (your own); warded: it gives the frame the Warded
-- badge and border (off for shields and school wards, up most of the time
-- or against one school only); note: the line under its name in the list.
local LIST = {
    { "Blessing of Protection", "external", true, "Paladin" },
    { "Blessing of Sacrifice", "external", true, "Paladin" },
    { "Divine Intervention", "external", true, "Paladin" },
    { "Power Word: Shield", "external", false, "Priest" },
    { "Shield Wall", "defensive", true, "Warrior" },
    { "Last Stand", "defensive", true, "Warrior" },
    { "Divine Shield", "defensive", true, "Paladin" },
    { "Divine Protection", "defensive", true, "Paladin" },
    { "Templar's Bulwark", "defensive", true, "Paladin · a Forever talent" },
    { "Ice Block", "defensive", true, "Mage" },
    { "Ice Barrier", "defensive", false, "Mage" },
    { "Mana Shield", "defensive", false, "Mage" },
    { "Fire Ward", "defensive", false, "Mage" },
    { "Frost Ward", "defensive", false, "Mage" },
    { "Evasion", "defensive", true, "Rogue" },
    { "Barkskin", "defensive", true, "Druid" },
    { "Frenzied Regeneration", "defensive", false, "Druid" },
    { "Deterrence", "defensive", true, "Hunter" },
    { "Shadow Ward", "defensive", false, "Warlock" },
    { "Stoneform", "defensive", false, "Dwarf racial" },
}

local byName, scanLines = {}, {}
for _, path in ipairs(SCANS) do
    local seen = {}
    for line in io.lines(path) do
        if line:sub(1, 1) == "#" then
            scanLines[#scanLines + 1] = line
        else
            local id, name = line:match("^(%d+)\t([^\t]*)")
            id = tonumber(id)
            if id and not seen[id] then
                seen[id] = true
                byName[name] = byName[name] or {}
                byName[name][id] = true
            end
        end
    end
end

local out = {
    "-- Data/Defensives.lua",
    "-- Generated by tools/gen_defensives.lua: SuuUI's default defensives for",
    "-- party and raid frames (Frames › Defensives), each with every spell ID of",
    "-- its name in the client. Don't edit by hand.",
    "",
    "local _, ns = ...",
    "",
    "ns.Defensives = {",
}
for _, e in ipairs(LIST) do
    local set = byName[e[1]]
    if not set then error("not in the client: " .. e[1]) end
    local ids = {}
    for id in pairs(set) do ids[#ids + 1] = id end
    table.sort(ids)
    out[#out + 1] = ("    { name = %q, kind = %q, ward = %s, note = %q, ids = { %s } },"):format(
        e[1], e[2], tostring(e[3]), e[4], table.concat(ids, ", "))
    print(("%-24s %-9s %d ids"):format(e[1], e[2], #ids))
end
out[#out + 1] = "}"
local f = assert(io.open(OUT, "w"))
f:write(table.concat(out, "\n"), "\n")
f:close()
print("-> " .. OUT)
