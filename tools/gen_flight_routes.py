# tools/gen_flight_routes.py
# Writes src/Data/FlightRoutes.lua: how far each flight master's route flies,
# for flight times before you have flown a route yourself; and
# src/Data/FlightPaths.lua: the way each route flies, for drawing it. From
# Forever's client tables (DB2) TaxiPath (the routes, one hop between two
# flight masters each), TaxiPathNode (each route's waypoints) and TaxiNodes
# (the flight masters), from wago.tools. A flight follows a Catmull-Rom curve
# through its waypoints; its length is measured along that curve, and its
# drawing is that curve made a few straight lines (none further than TOLERANCE
# yards off it).
#   sh tools/update_flight_routes.sh
#   (or: python3 -I tools/gen_flight_routes.py <dir with the CSVs> <build> src/Data/FlightRoutes.lua src/Data/FlightPaths.lua)
import csv, sys, os, math, collections
DIR, BUILD, OUT, OUT_PATHS = sys.argv[1:5]
TOLERANCE = 30  # yards

def table(name):
    return list(csv.DictReader(open(os.path.join(DIR, name + '.csv'), encoding='utf-8')))

# boats, zeppelins and the old nodes still in the client aren't flight masters
nodes = {}
for r in table('TaxiNodes'):
    name = r['Name_lang']
    if name.startswith('Transport,') or name.startswith('zzOLD'): continue
    nodes[int(r['ID'])] = name

points = collections.defaultdict(list)
for r in table('TaxiPathNode'):
    points[int(r['PathID'])].append((int(r['NodeIndex']), int(r['ContinentID']), int(r['Flags']), int(r['Delay']),
        float(r['Loc_0']), float(r['Loc_1']), float(r['Loc_2'])))

def curve(pts, steps=16):
    """The Catmull-Rom curve through pts, its ends held, as points steps to a waypoint."""
    out = [pts[0]]
    for i in range(len(pts) - 1):
        a, b, c = pts[max(i - 1, 0)], pts[i], pts[i + 1]
        d = pts[min(i + 2, len(pts) - 1)]
        for s in range(1, steps + 1):
            t = s / steps
            out.append(tuple(0.5 * (2 * p1 + (p2 - p0) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t * t
                + (3 * p1 - p0 - 3 * p2 + p3) * t * t * t) for p0, p1, p2, p3 in zip(a, b, c, d)))
    return out

def length(pts):
    """Yards along the Catmull-Rom curve through pts."""
    line = curve(pts)
    return sum(math.dist(line[i], line[i + 1]) for i in range(len(line) - 1))

def simplify(line, tolerance):
    """Douglas-Peucker on the map's plane (x, y): the fewest points within tolerance of line."""
    keep = [False] * len(line)
    keep[0] = keep[-1] = True
    todo = [(0, len(line) - 1)]
    while todo:
        i, j = todo.pop()
        (ax, ay), (bx, by) = line[i][:2], line[j][:2]
        dx, dy = bx - ax, by - ay
        l2 = dx * dx + dy * dy
        far, at = 0.0, None
        for k in range(i + 1, j):
            px, py = line[k][:2]
            t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / l2)) if l2 else 0.0
            d = math.hypot(px - ax - dx * t, py - ay - dy * t)
            if d > far: far, at = d, k
        if at is not None and far > tolerance:
            keep[at] = True
            todo += [(i, at), (at, j)]
    return [p for p, k in zip(line, keep) if k]

routes = collections.defaultdict(dict)   # from node -> {to node: yards}
paths = collections.defaultdict(dict)    # from node -> {to node: (continent, [(x, y), ...])}
left = 0
for r in table('TaxiPath'):
    src, dst = int(r['FromTaxiNode']), int(r['ToTaxiNode'])
    pts = sorted(points.get(int(r['ID']), []))
    # a stop on the way (a dock), a jump (Flags 1) or another continent: not a flight
    if src not in nodes or dst not in nodes or len(pts) < 2 or any(p[3] or p[2] & 1 for p in pts) \
            or len({p[1] for p in pts}) > 1:
        left += 1
        continue
    routes[src][dst] = round(length([p[4:] for p in pts]))
    paths[src][dst] = (pts[0][1], [(round(x), round(y)) for x, y, _ in simplify(curve([p[4:] for p in pts], 4), TOLERANCE)])

out = []
w = out.append
w('-- Data/FlightRoutes.lua (generated by tools/gen_flight_routes.py: do not edit)')
w("-- How far each of Forever's flight master routes flies, for flight times before you have flown it.")
w("--   Forever's client tables TaxiPath, TaxiPathNode and TaxiNodes, build %s (wago.tools)" % BUILD)
w('--   rebuild: sh tools/update_flight_routes.sh')
w('--   [from nodeID] = { [to nodeID] = yards, ... }  (one hop, flight master to flight master;')
w("--   nodeID as C_TaxiMap's nodes give it; a longer flight is its hops added up)")
w('')
w('local _, ns = ...')
w('')
w('ns.FlightRoutes = {')
for src in sorted(routes):
    w('    [%d] = { -- %s' % (src, nodes[src]))
    for dst in sorted(routes[src]):
        w('        [%d] = %d, -- %s' % (dst, routes[src][dst], nodes[dst]))
    w('    },')
w('}')
open(OUT, 'w', encoding='utf-8').write('\n'.join(out) + '\n')

out = []
w = out.append
w('-- Data/FlightPaths.lua (generated by tools/gen_flight_routes.py: do not edit)')
w("-- The way each of Forever's flight master routes flies, for drawing it on the map.")
w("--   Forever's client tables TaxiPath, TaxiPathNode and TaxiNodes, build %s (wago.tools)" % BUILD)
w('--   rebuild: sh tools/update_flight_routes.sh')
w('--   [from nodeID] = { [to nodeID] = { continentID, x1, y1, x2, y2, ... }, ... }  (one hop, as')
w('--   FlightRoutes.lua; world x, y in yards as C_Map.GetWorldPosFromMapPos gives them, the')
w('--   flown curve as straight lines no further than %d yards off it)' % TOLERANCE)
w('')
w('local _, ns = ...')
w('')
w('ns.FlightPaths = {')
for src in sorted(paths):
    w('    [%d] = { -- %s' % (src, nodes[src]))
    for dst in sorted(paths[src]):
        continent, line = paths[src][dst]
        w('        [%d] = { %d, %s }, -- %s' % (dst, continent, ', '.join('%d, %d' % p for p in line), nodes[dst]))
    w('    },')
w('}')
open(OUT_PATHS, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('gen_flight_routes: %d routes from %d flight masters (%d paths left out, %d points drawn), build %s'
    % (sum(len(v) for v in routes.values()), len(routes), left,
       sum(len(l) for v in paths.values() for _, l in v.values()), BUILD))
