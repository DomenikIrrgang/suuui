-- tools/presets_source.lua
-- The Cooldown Manager presets (plan step 1.7c), written as spell names. Not
-- loaded by the game: tools/gen_presets.lua turns every name into all the
-- spell IDs that carry exactly that name in Forever's client (the spell scan,
-- tools/data/forever_spells.tsv), so every rank is in and nothing is guessed.
-- A name the client doesn't have stops the generator.
--
-- Lists per preset:
--   essential, utility   cooldowns (the tracker uses the ranks you know)
--   buffs                buffs on you (from anyone unless mine = true)
--   debuffs              your debuffs on the target (always yours)
--   procs                proc auras on you
-- An entry is a name, or { "Name", mine = true } for an aura only you cast,
-- or a group: { group = "Seal", source = "mine"|"others"|"any", max = 1..4,
-- icon = "Member name", members = { "Name", ... } } (one slot for several).
-- Group names are plural ("Seals"), so they read as groups next to spells.
-- A member is a name, or { "Name", source = "mine"|"others"|"any" } for its
-- own source (else the group's; the slot gets an engine group per source).
-- In essential and utility a group (no source or max) is one cooldown: the
-- last member the character knows, so list them in order of preference
-- ({ group = "Shields", members = { "Divine Protection", "Divine Shield" } }
-- shows Divine Shield once learned); behaviour as for a cooldown, its effect
-- the shown member's own aura unless effectName says otherwise. Its members
-- keep passive talents' IDs and get the trainer check each.
-- In buffs, debuffs and procs, a collection: { collection = "Physical
-- Debuffs", hidden = true?, entries = { "Name", { "Name", missing = "hide" },
-- { group = ... } } }, entries shown side by side, each with its own
-- behaviour; hidden applies to all. One level: a collection in a collection,
-- or one in essential or utility, stops the generator.
--
-- Conditions (optional, `when = { ... }` on a { "Name", ... } entry, a
-- group, a { "Name", ... } member or a collection; copied as they are, see
-- UI/CooldownTracker.lua for when each is checked):
--   when = { match = "all"|"any",             -- default "all"
--            conditions = {
--              { type = "group", value = "solo"|"group"|"raid" },
--              { type = "classes", classes = { "DRUID", "WARLOCK", ... } },
--              { type = "role", roles = { "TANK"|"HEALER"|"DAMAGER", ... } },
--              { type = "stance", stances = { "battle"|"defensive"|"berserker"|
--                "caster"|"bear"|"cat"|"moonkin"|"travel"|"aquatic"|"stealth"|
--                "shadowform", ... } },
--              { type = "combat" },
--              { type = "instance", kinds = { "none"|"party"|"raid"|"pvp", ... } },
--              { type = "target", kinds = { "boss"|"elite"|"player"|"normal", ... } },
--            } }
--   ["not"] = true on a condition turns it around:
--   { "Battle Shout", when = { conditions = { { type = "group", value = "solo", ["not"] = true } } } }
-- A collection's `when` applies to everything in it. An unknown type, class
-- token, role, stance, instance or target kind, or an empty list, stops the
-- generator.
--
-- Behaviour (optional, on a { "Name", ... } entry or a group; the Cooldown
-- Manager's Behaviour panel, copied into the player's lists as the preset's
-- own; anything left out follows the list's setting):
--   cooldowns (essential, utility)
--     ready = "normal"|"glow"|"pulse"      how it looks when ready
--     pop = true|false                     the arcane flash coming ready
--     sound = "chime"|"ping"|"proc"|"warning"   when it comes ready
--     onCooldown = "dim"|"hide"            (default grey)
--     show = "ready"|"cooldown"            only when ready / only on cooldown
--     unusable = "hide"                    (default dim: no rage, wrong form)
--     border = "ink"|"gilt"|"muted"        the edge when ready
--     effect = "you"|"target"              while its buff on you / your debuff
--                                          on the target runs, that aura covers
--                                          the icon (its time and drain), so
--                                          the buff needs no entry of its own
--     effectName = "Aura name"             when the aura's name isn't the spell's
--   auras (buffs, debuffs, procs, and groups there)
--     source = "mine"|"others"|"any"       whose (groups: the group's source)
--     missing = "hide"|"grey"|"target"|"warn"|"remind"   while it isn't up
--                                          (default: buffs grey, debuffs
--                                          "target" = grey only with a hostile
--                                          target; remind: grey only while
--                                          missing, out of combat; for buffs
--                                          you keep up)
--     size = "small"|"large"               (default normal)
--     border = "ink"|"gilt"|"muted"; glow = true; digits = false (no timer);
--     stacks = false; expiring = 1..10     seconds the timer turns amber
--     soundAppear / soundStack / soundDrop = "chime"|"ping"|"proc"|"warning"
--   any entry: hidden = true               in the lists, off until shown
-- tree: the talent tree a preset belongs to (1-3, left to right as Forever
-- lays them out); 0 is Unspecced, for characters with no talent points. The
-- first preset of a tree is that spec's starting setup.
--
-- Names are Forever's, which differ from vanilla's in places: Curse of Doom
-- and Curse of Agony are "Bane of Doom" and "Bane of Agony", the trap effects are named like their traps, Faerie Fire
-- (Feral) is "Faerie Fire", Demonic Sacrifice's buffs are "Burning Shadow" and
-- "Touch of Fire". Blessing of Sanctuary, Elemental Mastery and Curse of
-- Shadow aren't in Forever's client at all. Trainers don't teach Gift of the
-- Wild, Prayer of Fortitude, Arcane Brilliance, Inferno, Fire Nova Totem (Fire
-- Nova is a spell), Lightwell, Desperate Prayer or Tranquilizing Shot, and Sanctity Aura isn't a
-- talent (checked against /suu probe class data in tools/data).
-- Forever's own class spells (IDs above a million) aren't in vanilla's lists:
-- Seal of Fury (Protection) so far; more turn up in characters' spellbooks.
--
-- The presets live in one file per class (tools/presets/<CLASS>.lua), the
-- groups they share in tools/presets/shared.lua.

local CLASSES = { "WARRIOR", "PALADIN", "HUNTER", "ROGUE", "PRIEST", "SHAMAN", "MAGE", "WARLOCK", "DRUID" }
local out = {}
-- a class file that doesn't load is reported and left out (the others still
-- generate)
for _, class in ipairs(CLASSES) do
    local ok, presets = pcall(dofile, ("tools/presets/%s.lua"):format(class))
    if ok then out[class] = presets else io.stderr:write(("presets of %s don't load: %s\n"):format(class, tostring(presets))) end
end
return out
