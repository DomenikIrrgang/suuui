local H = require("harness")

describe("Components.ScrollFrame", function()
    local host
    before_each(function()
        H.setup()
        host = H.parent(400, 400)
    end)

    -- The bar occupies its token width, the border inset it sits in, and a 1px gap
    -- keeping it clear of the viewport. The gap has no matching space token.
    local BAR_GAP = 1
    local function gutter() return H.token("sizeScrollbar") + H.token("borderWidth") + BAR_GAP end

    -- Vertical inset of the track inside the frame. Smaller than any space token.
    local TRACK_INSET_Y = 2

    local function scroller(w, h)
        return H.mount(H.C.ScrollFrame({ w = w or 200, h = h or 300 }, host))
    end

    describe("sizing", function()
        it("defaults to 200x300", function()
            H.expectSize(H.C.ScrollFrame({}, host), 200, 300)
        end)

        it("fills the outer frame with the viewport when no bar is needed", function()
            local s = scroller()
            H.expectSize(s._sf, 200, 300)
        end)

        it("sizes the bar track from the sizeScrollbar token", function()
            local s = scroller()
            H.expectSize(s._track, H.token("sizeScrollbar"), 300 - TRACK_INSET_Y * 2)
        end)

        it("insets the track from the right edge by the borderWidth token", function()
            local s = scroller()
            s:SetContentHeight(900)
            local sb, tb = H.box(s), H.box(s._track)
            expect(tb.right).eq(sb.right - H.token("borderWidth"))
            expect(tb.top).eq(sb.top + TRACK_INSET_Y)
        end)

        it("follows the borderWidth token when it changes", function()
            local s = scroller()
            s:SetContentHeight(900)
            H.T:CreateUserTheme("Thick", "Modern")
            H.T:SetUserToken("Thick", "borderWidth", 4)
            H.T:SetActive("Thick")
            local sb, tb = H.box(s), H.box(s._track)
            expect(tb.right).as("the track rides the border inset").eq(sb.right - 4)
            expect(s:GetContentWidth())
                .as("the gutter widens with the inset").eq(200 - (H.token("sizeScrollbar") + 4 + BAR_GAP))
        end)

        it("styles the track and thumb from the surface tokens", function()
            local s = scroller()
            H.expectTokenColor(H.backdropColor(s._track), "colorBgAlt")
            H.expectTokenColor(H.borderColor(s._track), "colorBorder")
            H.expectTokenColor(H.backdropColor(s._thumb), "colorAccent")
            H.expectTokenColor(H.borderColor(s._thumb), "colorBorder")
        end)

        it("derives the backdrop insets from the borderWidth token", function()
            local s = scroller()
            local bw = H.token("borderWidth")
            expect(s._track:GetBackdrop().insets)
                .deepEq({ left = bw, right = bw, top = bw, bottom = bw })
            expect(s._thumb:GetBackdrop().edgeSize).eq(bw)
        end)

        it("re-tints the thumb when the accent primitive changes", function()
            local s = scroller()
            H.T:CreateUserTheme("Loud", "Modern")
            H.T:SetUserToken("Loud", "colorBlue400", { 1, 0, 1, 1 })
            H.T:SetActive("Loud")
            expect(H.backdropColor(s._thumb)).deepEq({ 1, 0, 1, 1 })
            H.expectTokenColor(H.backdropColor(s._thumb), "colorAccent")
        end)

        it("re-applies a changed bar width token", function()
            local s = scroller()
            s:SetContentHeight(900)
            H.T:CreateUserTheme("Fat", "Modern")
            H.T:SetUserToken("Fat", "sizeScrollbar", 20)
            H.T:SetActive("Fat")
            H.expectSize(s._track, 20, nil)
            H.expectSize(s._thumb, 20, nil)
        end)
    end)

    describe("scrollbar visibility", function()
        it("hides the bar when the content fits", function()
            local s = scroller()
            expect(s._track:IsShown()).falsy()
        end)

        it("shows the bar once the content is taller than the viewport", function()
            local s = scroller()
            s:SetContentHeight(600)
            expect(s._track:IsShown()).truthy()
        end)

        it("insets the viewport by the gutter while the bar is visible", function()
            local s = scroller()
            s:SetContentHeight(600)
            H.expectSize(s._sf, 200 - gutter(), 300)
        end)

        it("restores the full viewport width when the content shrinks again", function()
            local s = scroller()
            s:SetContentHeight(600)
            s:SetContentHeight(100)
            expect(s._track:IsShown()).falsy()
            H.expectSize(s._sf, 200, 300)
        end)

        it("never lets the content sit underneath the bar", function()
            local s = scroller()
            s:SetContentHeight(600)
            H.expectNoOverlap({ s._content, s._track })
        end)

        it("reports the usable content width, accounting for the bar", function()
            local s = scroller()
            expect(s:GetContentWidth()).eq(200)
            s:SetContentHeight(600)
            expect(s:GetContentWidth()).eq(200 - gutter())
        end)

        it("emits SIZE_CHANGED when the bar appearing changes the usable width", function()
            local s = scroller()
            local spy = H.signalSpy(s, H.S.SIGNALS.SIZE_CHANGED)
            s:SetContentHeight(600)
            expect(spy.count).as("consumers must re-flow to the narrower width").gte(1)
        end)

        it("keeps the gutter out when the viewport shrinks below the old clamp", function()
            local col = H.Layout:CreateContainer({ parent = host, layout = "flow", dir = "vertical" })
            local s = H.C.ScrollFrame({ w = 200, h = 300 }, col:GetFrame())
            col:Add(s, { width = "fill", height = 300 })
            s:SetContentHeight(50)
            col:SetChildProps(s, { width = "fill", height = 200 })
            expect(s._track:IsShown()).as("50px of content never needs a bar").falsy()
            H.expectSize(s._sf, 400, 200)
            expect(s:GetContentWidth()).eq(400)
        end)

        it("reserves no gutter before any content height is reported", function()
            local col = H.Layout:CreateContainer({ parent = host, layout = "flow", dir = "vertical" })
            local s = H.C.ScrollFrame({ w = 200, h = 300 }, col:GetFrame())
            col:Add(s, { width = "fill", height = 200 })
            expect(s._track:IsShown()).as("props.h is a size, not a content height").falsy()
            expect(s:GetContentWidth()).eq(400)
        end)

        it("matches the content width to the viewport", function()
            local s = scroller()
            s:SetContentHeight(600)
            expect(s._content:GetWidth()).eq(s._sf:GetWidth())
        end)
    end)

    describe("content height", function()
        it("floors the content height at the viewport height", function()
            local s = scroller(200, 300)
            s:SetContentHeight(50)
            expect(s._content:GetHeight()).eq(300)
        end)

        it("takes a taller content height verbatim", function()
            local s = scroller(200, 300)
            s:SetContentHeight(1000)
            expect(s._content:GetHeight()).eq(1000)
        end)

        it("accepts a height reported through CONTENT_RESIZED", function()
            local s = scroller(200, 300)
            H.S:Emit(s, H.S.SIGNALS.CONTENT_RESIZED, 800)
            expect(s._content:GetHeight()).eq(800)
            expect(s._track:IsShown()).truthy()
        end)
    end)

    describe("thumb geometry", function()
        it("sizes the thumb in proportion to the visible fraction", function()
            local s = scroller(200, 300)
            s:SetContentHeight(600)
            local trackH = s._track:GetHeight()
            H.expectSize(s._thumb, nil, trackH * 0.5)
        end)

        it("never shrinks the thumb below the icon token", function()
            local s = scroller(200, 300)
            s:SetContentHeight(100000)
            expect(s._thumb:GetHeight()).eq(H.token("sizeIcon"))
        end)

        it("parks the thumb at the track top when unscrolled", function()
            local s = scroller(200, 300)
            s:SetContentHeight(600)
            H.expectOffset(s._thumb, s._track, 0, 0)
        end)

        it("moves the thumb to the track bottom at full scroll", function()
            local s = scroller(200, 300)
            s:SetContentHeight(600)
            s._sf:SetVerticalScroll(300)
            s:_updateBar()
            local tb, thb = H.box(s._track), H.box(s._thumb)
            expect(thb.bottom).near(tb.bottom, 0.5)
        end)

        it("keeps the thumb inside the track at every scroll position", function()
            local s = scroller(200, 300)
            s:SetContentHeight(900)
            for _, scroll in ipairs({ 0, 100, 300, 600 }) do
                s._sf:SetVerticalScroll(scroll)
                s:_updateBar()
                H.expectInside(s._thumb, s._track)
            end
        end)
    end)

    describe("mouse wheel", function()
        it("scrolls down by 20 per notch", function()
            local s = scroller(200, 300)
            s:SetContentHeight(600)
            H.scroll(s._sf, -1)
            expect(s._sf:GetVerticalScroll()).eq(20)
        end)

        it("scrolls back up", function()
            local s = scroller(200, 300)
            s:SetContentHeight(600)
            s._sf:SetVerticalScroll(100)
            H.scroll(s._sf, 1)
            expect(s._sf:GetVerticalScroll()).eq(80)
        end)

        it("stops at the top", function()
            local s = scroller(200, 300)
            s:SetContentHeight(600)
            H.scroll(s._sf, 1)
            expect(s._sf:GetVerticalScroll()).eq(0)
        end)

        it("stops at the bottom", function()
            local s = scroller(200, 300)
            s:SetContentHeight(600)
            for _ = 1, 50 do H.scroll(s._sf, -1) end
            expect(s._sf:GetVerticalScroll()).eq(300)
        end)

        it("does nothing when the content fits", function()
            local s = scroller(200, 300)
            H.scroll(s._sf, -1)
            expect(s._sf:GetVerticalScroll()).eq(0)
        end)

        it("emits SCROLL_CHANGED with the new offset", function()
            local s = scroller(200, 300)
            s:SetContentHeight(600)
            local spy = H.signalSpy(s, H.S.SIGNALS.SCROLL_CHANGED)
            H.scroll(s._sf, -1)
            expect(spy:arg(1)).eq(20)
        end)

        it("moves the content up as the scroll offset grows", function()
            local s = scroller(200, 300)
            s:SetContentHeight(600)
            local before = H.box(s._content).top
            H.scroll(s._sf, -1)
            expect(H.box(s._content).top).eq(before - 20)
        end)
    end)

    describe("thumb dragging", function()
        it("scrolls proportionally to the cursor movement", function()
            local s = scroller(200, 300)
            s:SetContentHeight(600)
            local trackH = s._track:GetHeight()
            local thumbH = s._thumb:GetHeight()

            H.cursor(0, 500)
            H.mouseDown(s._thumb, "LeftButton")
            H.cursor(0, 500 - (trackH - thumbH))
            H.tick(0.05)
            expect(s._sf:GetVerticalScroll()).as("a full track travel is a full scroll").eq(300)
        end)

        it("clamps at the ends of the range", function()
            local s = scroller(200, 300)
            s:SetContentHeight(600)
            H.cursor(0, 500)
            H.mouseDown(s._thumb, "LeftButton")
            H.cursor(0, 5000)
            H.tick(0.05)
            expect(s._sf:GetVerticalScroll()).eq(0)
            H.cursor(0, -5000)
            H.tick(0.05)
            expect(s._sf:GetVerticalScroll()).eq(300)
        end)

        it("stops tracking on release", function()
            local s = scroller(200, 300)
            s:SetContentHeight(600)
            H.cursor(0, 500)
            H.mouseDown(s._thumb, "LeftButton")
            H.mouseUp(s._thumb, "LeftButton")
            expect(s._thumb:GetScript("OnUpdate")).isNil()
            H.cursor(0, 100)
            H.tick(0.05)
            expect(s._sf:GetVerticalScroll()).eq(0)
        end)

        it("ignores non-left buttons", function()
            local s = scroller(200, 300)
            s:SetContentHeight(600)
            H.mouseDown(s._thumb, "RightButton")
            expect(s._thumb:GetScript("OnUpdate")).isNil()
        end)
    end)

    describe("ScrollToTop", function()
        it("resets the offset and emits SCROLL_CHANGED", function()
            local s = scroller(200, 300)
            s:SetContentHeight(600)
            s._sf:SetVerticalScroll(200)
            local spy = H.signalSpy(s, H.S.SIGNALS.SCROLL_CHANGED)
            s:ScrollToTop()
            expect(s._sf:GetVerticalScroll()).eq(0)
            expect(spy:arg(1)).eq(0)
        end)
    end)

    describe("layout integration", function()
        it("re-derives the bar when a parent layout resizes it", function()
            local col = H.Layout:CreateContainer({ parent = host, layout = "flow", dir = "vertical" })
            local s = H.C.ScrollFrame({ w = 200, h = 300 }, col:GetFrame())
            col:Add(s, { width = "fill", height = 150 })
            s:SetContentHeight(600)
            H.expectSize(s, 400, 150)
            H.expectSize(s._sf, 400 - gutter(), 150)
        end)

        it("lays content out inside the viewport through a container", function()
            local s = scroller(200, 300)
            local page = H.Layout:CreateContainer({
                parent = s:GetContent(), layout = "flow", dir = "vertical", gap = 4,
                w = s:GetContentWidth(),
            })
            local rows = {}
            for i = 1, 20 do
                rows[i] = H.C.Frame({ w = 10, h = 30 }, page:GetFrame())
                page:Add(rows[i], { width = "fill", height = 30 })
            end
            local _, contentH = page:GetContentSize()
            s:SetContentHeight(contentH)
            expect(contentH).eq(20 * 30 + 19 * 4)
            expect(s._track:IsShown()).truthy()
            H.expectStackedVertically(rows, 4)
        end)

        it("treats SetEnabled as a no-op", function()
            local s = scroller()
            expect(function() s:SetEnabled(false) end).notThrows()
        end)

        it("keeps the standard accessors and reports visibility", function()
            local s = scroller(200, 300)
            local spy = H.signalSpy(s, H.S.SIGNALS.VISIBILITY_CHANGED)
            expect(s:GetFrame()).eq(s._f)
            expect(s:GetWidth()).eq(200)
            expect(s:GetHeight()).eq(300)
            s:Hide()
            expect(s:IsShown()).falsy()
            s:Show()
            expect(spy.count).eq(2)
            expect(spy:arg(1)).truthy()
        end)

        it("reports an explicit SetSize through the frame's resize hook", function()
            local s = scroller(200, 300)
            local spy = H.signalSpy(s, H.S.SIGNALS.SIZE_CHANGED)
            s:SetSize(260, 200)
            H.expectSize(s, 260, 200)
            expect(spy.count).as("the resize hook reports it, not SetSize").gte(1)
        end)

        it("drops its drag ticker on Destroy", function()
            local s = scroller(200, 300)
            s:SetContentHeight(600)
            H.mouseDown(s._thumb, "LeftButton")
            s:Destroy()
            expect(s._thumb:GetScript("OnUpdate")).isNil()
        end)
    end)
end)

describe("TextMetrics", function()
    before_each(function() H.setup() end)

    it("measures text free of any layout-assigned width", function()
        local w, h = H.SuuUI.TextMetrics.Measure("A moderately long caption", "Fonts/FRIZQT__.TTF", 13)
        expect(w).eq(H.textWidth("A moderately long caption", 13))
        expect(h).eq(H.lineHeight(13))
    end)

    it("does not ratchet down across repeated calls", function()
        local first = H.SuuUI.TextMetrics.Measure("Stable caption", "Fonts/FRIZQT__.TTF", 13)
        for _ = 1, 10 do
            expect(H.SuuUI.TextMetrics.Measure("Stable caption", "Fonts/FRIZQT__.TTF", 13)).eq(first)
        end
    end)

    it("scales with the requested font size", function()
        local small = H.SuuUI.TextMetrics.Measure("abc", "Fonts/FRIZQT__.TTF", 10)
        local large = H.SuuUI.TextMetrics.Measure("abc", "Fonts/FRIZQT__.TTF", 20)
        expect(large).eq(small * 2)
    end)

    it("returns zero width for empty text", function()
        expect(H.SuuUI.TextMetrics.Measure("", "Fonts/FRIZQT__.TTF", 13)).eq(0)
    end)

    it("treats nil text as empty", function()
        expect(function() H.SuuUI.TextMetrics.Measure(nil, "Fonts/FRIZQT__.TTF", 13) end).notThrows()
    end)

    it("keeps its probe hidden and out of any layout", function()
        H.SuuUI.TextMetrics.Measure("x", "Fonts/FRIZQT__.TTF", 13)
        local probeHost = H.env.SuuUI_textMetrics_probe
        expect(probeHost).notNil()
        expect(probeHost:IsShown()).falsy()
    end)

    it("measures a different face differently", function()
        local wide   = H.SuuUI.TextMetrics.Measure("hello", "Fonts/FRIZQT__.TTF", 13)
        local narrow = H.SuuUI.TextMetrics.Measure("hello", "Fonts/ARIALN.TTF", 13)
        expect(narrow).lt(wide)
    end)

    describe("CanLoadFont", function()
        it("accepts a face the client ships", function()
            expect(H.SuuUI.TextMetrics.CanLoadFont("Fonts/ARIALN.TTF")).truthy()
        end)

        it("reports false for a missing file without raising", function()
            -- The client raises "Invalid font asset" rather than returning false, so the
            -- probe is protected. Unguarded, this unwound out of the login handler.
            expect(H.SuuUI.TextMetrics.CanLoadFont("Interface/AddOns/Nope/gone.ttf"))
                .falsy()
        end)

        it("reports false for junk input", function()
            for _, bad in ipairs({ "", "GameFontWhite", "not a path" }) do
                expect(H.SuuUI.TextMetrics.CanLoadFont(bad)).as(bad).falsy()
            end
            expect(H.SuuUI.TextMetrics.CanLoadFont(nil)).falsy()
            expect(H.SuuUI.TextMetrics.CanLoadFont(12)).falsy()
        end)

        it("leaves the probe's own face untouched, so measuring still works", function()
            local before = H.SuuUI.TextMetrics.Measure("hello", "Fonts/ARIALN.TTF", 13)
            H.SuuUI.TextMetrics.CanLoadFont("Interface/AddOns/Nope/gone.ttf")
            expect(H.SuuUI.TextMetrics.Measure("hello", "Fonts/ARIALN.TTF", 13)).eq(before)
        end)
    end)

    it("degrades instead of raising when asked to measure an unloadable face", function()
        expect(function()
            H.SuuUI.TextMetrics.Measure("x", "Interface/AddOns/Nope/gone.ttf", 13)
        end).notThrows()
    end)
end)
