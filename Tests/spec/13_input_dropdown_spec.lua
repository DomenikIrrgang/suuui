local H = require("harness")

describe("Components.Input", function()
    local host
    before_each(function()
        H.setup()
        host = H.parent(300, 200)
    end)

    describe("sizing", function()
        it("defaults to 160 wide", function()
            H.expectSize(H.C.Input({}, host), 160, nil)
        end)

        it("derives its height from sizeControlMd floored by the font", function()
            H.expectSize(H.C.Input({}, host), nil, H.controlHeight("sizeControlMd"))
        end)

        it("grows when the font token outgrows the size token", function()
            local i = H.C.Input({}, host)
            H.T:CreateUserTheme("Big", "Modern")
            H.T:SetUserToken("Big", "fontSizeMd", 30)
            H.T:SetActive("Big")
            H.expectSize(i, nil, 30 + H.token("spaceXs") * 2)
        end)

        it("reports the new height so the containing layout re-flows", function()
            local col = H.Layout:CreateContainer({ parent = host, layout = "flow", dir = "vertical" })
            local i = H.C.Input({}, col:GetFrame())
            col:Add(i, { width = 140 })
            local spy = H.signalSpy(i, H.S.SIGNALS.SIZE_CHANGED)
            H.T:CreateUserTheme("Big", "Modern")
            H.T:SetUserToken("Big", "fontSizeMd", 30)
            H.T:SetActive("Big")
            expect(spy.count).gte(1)
        end)

        it("keeps a pinned height across theme changes", function()
            local i = H.C.Input({ h = 18 }, host)
            H.T:CreateUserTheme("Big", "Modern")
            H.T:SetUserToken("Big", "fontSizeMd", 30)
            H.T:SetActive("Big")
            H.expectSize(i, nil, 18)
        end)

        it("emits SIZE_CHANGED once from an explicit resize", function()
            local i = H.C.Input({}, host)
            local spy = H.signalSpy(i, H.S.SIGNALS.SIZE_CHANGED)
            i:SetSize(100, 30)
            expect(spy.count).eq(1)
            expect(spy:arg(2)).eq(30)
        end)

        it("emits SIZE_CHANGED when a parent layout resizes it", function()
            local col = H.Layout:CreateContainer({ parent = host, layout = "flow", dir = "vertical" })
            local i = H.C.Input({}, col:GetFrame())
            local spy = H.signalSpy(i, H.S.SIGNALS.SIZE_CHANGED)
            col:Add(i, { width = "fill", height = 40 })
            expect(spy.count).gte(1)
            H.expectSize(i, 300, 40)
        end)

        it("drops token sizing after SetSize", function()
            local i = H.C.Input({}, host)
            i:SetSize(100, 16)
            H.T:CreateUserTheme("Big", "Modern")
            H.T:SetUserToken("Big", "fontSizeMd", 30)
            H.T:SetActive("Big")
            H.expectSize(i, 100, 16)
        end)

        it("insets the edit box inside the frame border", function()
            local i = H.mount(H.C.Input({ w = 160 }, host))
            H.expectOffset(i._eb, i:GetFrame(), 4, 2)
            H.expectSize(i._eb, 160 - 8, i:GetHeight() - 4)
        end)
    end)

    describe("value", function()
        it("starts with the given value", function()
            expect(H.C.Input({ value = "hello" }, host):GetValue()).eq("hello")
        end)

        it("starts empty with no value", function()
            expect(H.C.Input({}, host):GetValue()).eq("")
        end)

        it("does not emit TEXT_CHANGED for the initial value", function()
            local i = H.C.Input({ value = "preset" }, host)
            local spy = H.signalSpy(i, H.S.SIGNALS.TEXT_CHANGED)
            expect(spy.count).eq(0)
        end)

        it("sets the value silently with SetValue", function()
            local i = H.C.Input({}, host)
            local spy = H.signalSpy(i, H.S.SIGNALS.TEXT_CHANGED)
            local changes = 0
            i = H.C.Input({ onChange = function() changes = changes + 1 end }, host)
            spy = H.signalSpy(i, H.S.SIGNALS.TEXT_CHANGED)
            i:SetValue("quiet")
            expect(i:GetValue()).eq("quiet")
            expect(spy.count).as("SetValue must not echo back as a change").eq(0)
            expect(changes).eq(0)
        end)

        it("treats a nil SetValue as clearing the field", function()
            local i = H.C.Input({ value = "x" }, host)
            i:SetValue(nil)
            expect(i:GetValue()).eq("")
        end)

        it("rewinds the cursor on SetValue so long values show from the start", function()
            local i = H.C.Input({}, host)
            i:SetValue("a fairly long stored value")
            expect(i._eb:GetCursorPosition()).eq(0)
        end)

        it("leaves the cursor alone while the user is editing", function()
            local i = H.C.Input({}, host)
            i:SetFocus()
            i:SetValue("typed")
            expect(i._eb:GetCursorPosition()).as("do not fight the user's caret").eq(5)
        end)

        it("respects the default max letters", function()
            expect(H.C.Input({}, host)._eb:GetMaxLetters()).eq(255)
        end)

        it("respects an explicit maxChars", function()
            local i = H.C.Input({ maxChars = 4 }, host)
            i:SetValue("abcdefgh")
            expect(i:GetValue()).eq("abcd")
        end)
    end)

    describe("editing", function()
        it("emits TEXT_CHANGED and calls onChange as the user types", function()
            local seen
            local i = H.C.Input({ onChange = function(t) seen = t end }, host)
            local spy = H.signalSpy(i, H.S.SIGNALS.TEXT_CHANGED)
            H.typeText(i, "abc")
            expect(seen).eq("abc")
            expect(spy:arg(1)).eq("abc")
        end)

        it("emits SUBMITTED and calls onEnter on Enter", function()
            local entered
            local i = H.C.Input({ onEnter = function(t) entered = t end }, host)
            local spy = H.signalSpy(i, H.C.INPUT_SIGNALS.SUBMITTED)
            H.typeText(i, "done")
            H.pressEnter(i)
            expect(entered).eq("done")
            expect(spy:arg(1)).eq("done")
        end)

        it("releases focus on Enter", function()
            local i = H.C.Input({}, host)
            i:SetFocus()
            H.pressEnter(i)
            expect(i._eb:HasFocus()).falsy()
        end)

        it("releases focus on Escape without submitting", function()
            local i = H.C.Input({}, host)
            local spy = H.signalSpy(i, H.C.INPUT_SIGNALS.SUBMITTED)
            i:SetFocus()
            H.pressEscape(i)
            expect(i._eb:HasFocus()).falsy()
            expect(spy.count).eq(0)
        end)

        it("emits FOCUSED and UNFOCUSED", function()
            local i = H.C.Input({}, host)
            local focused = H.signalSpy(i, H.S.SIGNALS.FOCUSED)
            local blurred = H.signalSpy(i, H.S.SIGNALS.UNFOCUSED)
            i:SetFocus()
            i._eb:ClearFocus()
            expect(focused.count).eq(1)
            expect(blurred.count).eq(1)
        end)

        it("disables the edit box when disabled", function()
            local i = H.C.Input({}, host)
            i:SetEnabled(false)
            expect(i._eb:IsEnabled()).falsy()
        end)
    end)

    describe("theming", function()
        it("uses the alt surface and border tokens at rest", function()
            local i = H.C.Input({}, host)
            H.expectTokenColor(H.backdropColor(i), "colorBgAlt")
            H.expectTokenColor(H.borderColor(i), "colorBorder")
        end)

        it("shows the focus border while focused", function()
            local i = H.C.Input({}, host)
            i:SetFocus()
            H.expectTokenColor(H.borderColor(i), "colorBorderFocus")
            i._eb:ClearFocus()
            H.expectTokenColor(H.borderColor(i), "colorBorder")
        end)

        it("shows the focus border while the cursor is over the edit box", function()
            local i = H.C.Input({}, host)
            H.hover(i._eb)
            H.expectTokenColor(H.borderColor(i), "colorBorderFocus")
            H.unhover(i._eb)
            H.expectTokenColor(H.borderColor(i), "colorBorder")
        end)

        it("keeps the focus border when hover ends but focus remains", function()
            local i = H.C.Input({}, host)
            i:SetFocus()
            H.hover(i._eb)
            H.unhover(i._eb)
            H.expectTokenColor(H.borderColor(i), "colorBorderFocus")
        end)

        it("shows the focus border from the border ring around the edit box", function()
            -- The edit box is inset, so the frame owns the surrounding ring and has to
            -- take mouse input for that hover to register.
            local i = H.C.Input({}, host)
            expect(i:GetFrame():IsMouseEnabled()).truthy()
            expect(H.hover(i:GetFrame())).truthy()
            H.expectTokenColor(H.borderColor(i), "colorBorderFocus")
            H.unhover(i:GetFrame())
            H.expectTokenColor(H.borderColor(i), "colorBorder")
        end)

        it("uses the medium font and text colour", function()
            local i = H.C.Input({}, host)
            local _, size = i._eb:GetFont()
            expect(size).eq(H.token("fontSizeMd"))
            H.expectTokenColor({ i._eb:GetTextColor() }, "colorText")
        end)
    end)
end)

describe("Components.Dropdown", function()
    local host
    local options

    before_each(function()
        H.setup()
        host = H.parent(300, 200)
        options = {
            { value = "solid", label = "Solid" },
            { value = "flat",  label = "Flat" },
            { value = "glass", label = "Glass" },
        }
    end)

    local function rowHeight() return H.controlHeight("sizeControlMd") end

    describe("sizing", function()
        it("defaults to 160 wide", function()
            H.expectSize(H.C.Dropdown({ options = options }, host), 160, nil)
        end)

        it("derives its height from sizeControlLg floored by the font", function()
            H.expectSize(H.C.Dropdown({ options = options }, host), nil,
                H.controlHeight("sizeControlLg"))
        end)

        it("grows when the font token outgrows the size token", function()
            local d = H.C.Dropdown({ options = options }, host)
            H.T:CreateUserTheme("Big", "Modern")
            H.T:SetUserToken("Big", "fontSizeMd", 30)
            H.T:SetActive("Big")
            H.expectSize(d, nil, 30 + H.token("spaceXs") * 2)
        end)

        it("keeps a pinned height", function()
            local d = H.C.Dropdown({ options = options, h = 20 }, host)
            H.T:CreateUserTheme("Big", "Modern")
            H.T:SetUserToken("Big", "fontSizeMd", 30)
            H.T:SetActive("Big")
            H.expectSize(d, nil, 20)
        end)

        it("emits SIZE_CHANGED once from an explicit resize", function()
            local d = H.C.Dropdown({ options = options }, host)
            local spy = H.signalSpy(d, H.S.SIGNALS.SIZE_CHANGED)
            d:SetSize(200, 30)
            expect(spy.count).eq(1)
            expect(spy:arg(1)).eq(200)
        end)

        it("emits SIZE_CHANGED when a parent layout resizes it", function()
            local col = H.Layout:CreateContainer({ parent = host, layout = "flow", dir = "vertical" })
            local d = H.C.Dropdown({ options = options }, col:GetFrame())
            local spy = H.signalSpy(d, H.S.SIGNALS.SIZE_CHANGED)
            col:Add(d, { width = "fill", height = 28 })
            expect(spy.count).gte(1)
            H.expectSize(d, 300, 28)
        end)

        it("leaves room for the arrow beside the label", function()
            local d = H.mount(H.C.Dropdown({ options = options, value = "solid", w = 160 }, host))
            H.expectOffset(d._selText, d:GetFrame(), 6, nil)
            H.expectSize(d._selText, 160 - 6 - 16, nil)
            local db, ab = H.box(d), H.box(d._arrow)
            expect(ab.right).eq(db.right - 4)
            expect(ab.width).eq(8)
            H.expectNoOverlap({ d._selText, d._arrow })
        end)
    end)

    describe("selection", function()
        it("shows the label of the initial value", function()
            local d = H.C.Dropdown({ options = options, value = "flat" }, host)
            expect(d:GetValue()).eq("flat")
            expect(d._selText:GetText()).eq("Flat")
        end)

        it("shows nothing when no value is given", function()
            local d = H.C.Dropdown({ options = options }, host)
            expect(d:GetValue()).isNil()
            expect(d._selText:GetText()).eq("")
        end)

        it("updates the label from SetValue without emitting", function()
            local d = H.C.Dropdown({ options = options }, host)
            local spy = H.signalSpy(d, H.S.SIGNALS.VALUE_CHANGED)
            d:SetValue("glass")
            expect(d._selText:GetText()).eq("Glass")
            expect(spy.count).eq(0)
        end)

        it("stores an unknown value but leaves the label alone", function()
            local d = H.C.Dropdown({ options = options, value = "solid" }, host)
            d:SetValue("nonexistent")
            expect(d:GetValue()).eq("nonexistent")
            expect(d._selText:GetText()).eq("Solid")
        end)
    end)

    describe("panel", function()
        it("starts hidden", function()
            local d = H.C.Dropdown({ options = options }, host)
            expect(d._panel:IsShown()).falsy()
        end)

        it("opens on click", function()
            local d = H.mount(H.C.Dropdown({ options = options }, host))
            H.click(d)
            expect(d._panel:IsShown()).truthy()
        end)

        it("closes on a second click", function()
            local d = H.mount(H.C.Dropdown({ options = options }, host))
            H.click(d)
            H.click(d)
            H.runAnimations()
            expect(d._panel:IsShown()).falsy()
        end)

        it("sizes the panel to the option count plus padding", function()
            local d = H.mount(H.C.Dropdown({ options = options, w = 160 }, host))
            H.click(d)
            H.expectSize(d._panel, 160, #options * rowHeight() + H.token("spaceXs") * 2)
        end)

        it("hangs the panel just below the dropdown", function()
            local d = H.mount(H.C.Dropdown({ options = options, w = 160 }, host))
            H.click(d)
            local db, pb = H.box(d), H.box(d._panel)
            expect(pb.left).eq(db.left)
            expect(pb.top).as("2px of breathing room").eq(db.bottom + 2)
        end)

        it("raises the panel to the tooltip strata so it floats over everything", function()
            local d = H.mount(H.C.Dropdown({ options = options }, host))
            H.click(d)
            expect(d._panel:GetFrameStrata()).eq("TOOLTIP")
        end)

        it("stacks one row per option, in order, inside the panel", function()
            local d = H.mount(H.C.Dropdown({ options = options }, host))
            H.click(d)
            expect(#d._rows).eq(3)
            for i, opt in ipairs(options) do
                expect(d._rows[i]._lbl:GetText()).eq(opt.label)
                H.expectInside(d._rows[i], d._panel)
            end
            H.expectStackedVertically(d._rows, 0)
            H.expectNoOverlap(d._rows)
        end)

        it("fades the panel in to full opacity", function()
            local d = H.mount(H.C.Dropdown({ options = options }, host))
            H.click(d)
            expect(d._panel:GetAlpha()).eq(0)
            H.runAnimations()
            expect(d._panel:GetAlpha()).eq(1)
        end)

        it("re-uses row frames across open cycles", function()
            local d = H.mount(H.C.Dropdown({ options = options }, host))
            H.click(d)
            local firstRow = d._rows[1]
            H.click(d)
            H.runAnimations()
            H.click(d)
            expect(d._rows[1]).as("rows are pooled, not rebuilt").eq(firstRow)
        end)

        it("handles an empty option list", function()
            local d = H.mount(H.C.Dropdown({ options = {} }, host))
            expect(function() H.click(d) end).notThrows()
            expect(#d._rows).eq(0)
        end)

        it("handles a missing options prop", function()
            local d = H.mount(H.C.Dropdown({}, host))
            expect(function() H.click(d) end).notThrows()
        end)
    end)

    describe("choosing an option", function()
        it("emits VALUE_CHANGED with new and old, and calls onChange", function()
            local seen
            local d = H.mount(H.C.Dropdown({ options = options, value = "solid",
                                             onChange = function(v) seen = v end }, host))
            local spy = H.signalSpy(d, H.S.SIGNALS.VALUE_CHANGED)
            H.click(d)
            H.click(d._rows[2])
            expect(seen).eq("flat")
            expect(spy:arg(1)).eq("flat")
            expect(spy:arg(2)).eq("solid")
        end)

        it("updates the visible label and closes the panel", function()
            local d = H.mount(H.C.Dropdown({ options = options, value = "solid" }, host))
            H.click(d)
            H.click(d._rows[3])
            H.runAnimations()
            expect(d._selText:GetText()).eq("Glass")
            expect(d._panel:IsShown()).falsy()
        end)

        it("highlights a row on hover and restores it on leave", function()
            local d = H.mount(H.C.Dropdown({ options = options }, host))
            H.click(d)
            local row = d._rows[1]
            H.hover(row)
            H.expectTokenColor({ row:GetBackdropColor() }, "colorBgHover")
            H.unhover(row)
            H.expectTokenColor({ row:GetBackdropColor() }, "colorBgAlt")
        end)
    end)

    describe("click-away", function()
        it("closes when a click lands outside the panel and the dropdown", function()
            local d = H.mount(H.C.Dropdown({ options = options }, host))
            H.click(d)
            H.runAnimations()
            H.cursor(900, 700)
            H.setMouseDown("LeftButton", true)
            H.tick(0.05)
            H.setMouseDown("LeftButton", false)
            H.tick(0.05)
            H.runAnimations()
            expect(d._panel:IsShown()).falsy()
        end)

        it("stays open for a click inside the panel", function()
            local d = H.mount(H.C.Dropdown({ options = options }, host))
            H.click(d)
            H.runAnimations()
            local pb = H.box(d._panel)
            H.cursor(pb.left + 5, H.state.screenHeight - pb.bottom + 5)
            H.setMouseDown("LeftButton", true)
            H.tick(0.05)
            H.setMouseDown("LeftButton", false)
            H.tick(0.05)
            expect(d._panel:IsShown()).truthy()
        end)

        it("ignores the click that opened it", function()
            local d = H.mount(H.C.Dropdown({ options = options }, host))
            H.cursorOn(d)
            H.click(d)
            H.tick(0.05)
            expect(d._panel:IsShown()).truthy()
        end)
    end)

    describe("options and lifecycle", function()
        it("replaces the option list and closes the panel", function()
            local d = H.mount(H.C.Dropdown({ options = options, value = "solid" }, host))
            H.click(d)
            d:SetOptions({ { value = "solid", label = "Solid v2" } })
            H.runAnimations()
            expect(d._panel:IsShown()).falsy()
            expect(d._selText:GetText()).eq("Solid v2")
        end)

        it("treats a nil option list as empty", function()
            local d = H.mount(H.C.Dropdown({ options = options }, host))
            d:SetOptions(nil)
            H.click(d)
            expect(#d._rows).eq(0)
        end)

        it("closes the panel when hidden", function()
            local d = H.mount(H.C.Dropdown({ options = options }, host))
            H.click(d)
            d:Hide()
            H.runAnimations()
            expect(d._panel:IsShown()).falsy()
        end)

        it("stops receiving clicks when disabled", function()
            local d = H.mount(H.C.Dropdown({ options = options }, host))
            d:SetEnabled(false)
            expect(H.click(d)).falsy()
            H.forceClick(d)
            expect(d._panel:IsShown()).as("internal guard also holds").falsy()
        end)

        it("drops its panel from the shared floating host on Destroy", function()
            local floating = H.Layout:GetFloatingHost()
            local d = H.mount(H.C.Dropdown({ options = options }, host))
            local before = #floating:GetChildren()
            d:Destroy()
            expect(#floating:GetChildren()).eq(before - 1)
            expect(d._panel:IsShown()).falsy()
        end)

        it("leaves the shared floating host alive after Destroy", function()
            local d = H.mount(H.C.Dropdown({ options = options }, host))
            d:Destroy()
            expect(H.Layout:GetFloatingHost():GetFrame():IsShown()).truthy()
        end)
    end)
end)
