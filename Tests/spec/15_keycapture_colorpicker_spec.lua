local H = require("harness")

describe("Components.KeyCapture", function()
    local host
    before_each(function()
        H.setup()
        host = H.parent(300, 100)
        H.mods({})
    end)

    it("shows the placeholder when unbound", function()
        local k = H.C.KeyCapture({}, host)
        expect(k:GetValue()).eq("")
        expect(k._btn:GetLabel()).eq("Not Bound")
    end)

    it("honours a custom placeholder", function()
        local k = H.C.KeyCapture({ placeholder = "Click to bind" }, host)
        expect(k._btn:GetLabel()).eq("Click to bind")
    end)

    it("shows an existing binding as its label", function()
        local k = H.C.KeyCapture({ value = "CTRL-F1" }, host)
        expect(k._btn:GetLabel()).eq("CTRL-F1")
    end)

    it("applies a minimum width so long bindings fit", function()
        expect(H.C.KeyCapture({}, host):GetWidth()).gte(120)
    end)

    it("honours a custom minW", function()
        expect(H.C.KeyCapture({ minW = 200 }, host):GetWidth()).gte(200)
    end)

    it("keeps the catcher disabled until capture starts", function()
        local k = H.C.KeyCapture({}, host)
        expect(k._catcher:IsShown()).falsy()
        expect(k._catcher:IsKeyboardEnabled()).falsy()
    end)

    it("enters capture mode on click", function()
        local k = H.C.KeyCapture({}, host)
        local spy = H.signalSpy(k, H.S.SIGNALS.CLICKED)
        H.click(k)
        expect(k._capturing).truthy()
        expect(k._btn:GetLabel()).eq("Press key...")
        expect(k._catcher:IsKeyboardEnabled()).truthy()
        expect(spy.count).eq(1)
    end)

    it("captures a plain key and emits VALUE_CHANGED with new and old", function()
        local k = H.C.KeyCapture({ value = "F2" }, host)
        local spy = H.signalSpy(k, H.S.SIGNALS.VALUE_CHANGED)
        H.click(k)
        expect(H.key(k._catcher, "F1")).truthy()
        expect(k:GetValue()).eq("F1")
        expect(spy:arg(1)).eq("F1")
        expect(spy:arg(2)).eq("F2")
        expect(k._btn:GetLabel()).eq("F1")
    end)

    it("leaves capture mode after a successful capture", function()
        local k = H.C.KeyCapture({}, host)
        H.click(k)
        H.key(k._catcher, "F1")
        expect(k._capturing).falsy()
        expect(k._catcher:IsShown()).falsy()
        expect(k._catcher:IsKeyboardEnabled()).falsy()
    end)

    it("prefixes held modifiers in CTRL, ALT, SHIFT order", function()
        local k = H.C.KeyCapture({}, host)
        H.mods({ ctrl = true, alt = true, shift = true })
        H.click(k)
        H.key(k._catcher, "K")
        expect(k:GetValue()).eq("CTRL-ALT-SHIFT-K")
    end)

    it("prefixes only the modifiers actually held", function()
        local k = H.C.KeyCapture({}, host)
        H.mods({ shift = true })
        H.click(k)
        H.key(k._catcher, "K")
        expect(k:GetValue()).eq("SHIFT-K")
    end)

    it("ignores bare modifier presses and keeps capturing", function()
        local k = H.C.KeyCapture({}, host)
        H.click(k)
        for _, key in ipairs({ "LSHIFT", "RSHIFT", "LCTRL", "RCTRL", "LALT", "RALT", "UNKNOWN" }) do
            H.key(k._catcher, key)
            expect(k:GetValue()).as(key .. " must not bind").eq("")
            expect(k._capturing).truthy()
        end
        H.key(k._catcher, "Q")
        expect(k:GetValue()).eq("Q")
    end)

    it("cancels on Escape, restoring the previous binding", function()
        local k = H.C.KeyCapture({ value = "F3" }, host)
        local spy = H.signalSpy(k, H.S.SIGNALS.VALUE_CHANGED)
        H.click(k)
        H.key(k._catcher, "ESCAPE")
        expect(k:GetValue()).eq("F3")
        expect(k._btn:GetLabel()).eq("F3")
        expect(k._capturing).falsy()
        expect(spy.count).eq(0)
    end)

    it("cancels back to the placeholder when there was no binding", function()
        local k = H.C.KeyCapture({}, host)
        H.click(k)
        H.key(k._catcher, "ESCAPE")
        expect(k._btn:GetLabel()).eq("Not Bound")
    end)

    it("ignores keys when not capturing", function()
        local k = H.C.KeyCapture({}, host)
        k._catcher:EnableKeyboard(true)
        k._catcher:Show()
        H.key(k._catcher, "F1")
        expect(k:GetValue()).eq("")
    end)

    it("ignores a second click while already capturing", function()
        local k = H.C.KeyCapture({}, host)
        local spy = H.signalSpy(k, H.S.SIGNALS.CLICKED)
        H.click(k)
        H.click(k)
        expect(spy.count).eq(1)
    end)

    it("sets a binding silently with SetValue", function()
        local k = H.C.KeyCapture({}, host)
        local spy = H.signalSpy(k, H.S.SIGNALS.VALUE_CHANGED)
        k:SetValue("ALT-X")
        expect(k:GetValue()).eq("ALT-X")
        expect(k._btn:GetLabel()).eq("ALT-X")
        expect(spy.count).eq(0)
    end)

    it("shows the placeholder for an empty SetValue", function()
        local k = H.C.KeyCapture({ value = "F1" }, host)
        k:SetValue("")
        expect(k._btn:GetLabel()).eq("Not Bound")
    end)

    it("treats a nil SetValue as unbound", function()
        local k = H.C.KeyCapture({ value = "F1" }, host)
        k:SetValue(nil)
        expect(k:GetValue()).eq("")
    end)

    it("stops capturing when disabled", function()
        local k = H.C.KeyCapture({}, host)
        k:SetEnabled(false)
        expect(H.click(k)).as("the underlying button loses mouse input").falsy()
        expect(k._capturing).falsy()
    end)

    it("relays the button's re-fit as its own SIZE_CHANGED", function()
        local k = H.C.KeyCapture({}, host)
        local spy = H.signalSpy(k, H.S.SIGNALS.SIZE_CHANGED)
        k:SetValue("CTRL-SHIFT-NUMPADDIVIDE")
        expect(spy.count).as("layouts need to hear the button grew").gte(1)
    end)

    it("leaves capture mode when hidden", function()
        local k = H.C.KeyCapture({}, host)
        H.click(k)
        k:Hide()
        expect(k._capturing).falsy()
    end)

    it("reads geometry and visibility through the wrapped button", function()
        local k = H.C.KeyCapture({}, host)
        expect(k:GetFrame()).as("GetFrame reaches the button's frame").eq(k._btn:GetFrame())
        expect(k:GetWidth()).eq(k._btn:GetWidth())
        expect(k:GetHeight()).eq(k._btn:GetHeight())
        expect(k:IsShown()).truthy()
    end)

    it("resizes the wrapped button from SetSize", function()
        local k = H.C.KeyCapture({}, host)
        k:SetSize(200, 30)
        H.expectSize(k, 200, 30)
    end)

    it("emits VISIBILITY_CHANGED from Show and Hide", function()
        local k = H.C.KeyCapture({}, host)
        local spy = H.signalSpy(k, H.S.SIGNALS.VISIBILITY_CHANGED)
        k:Hide()
        expect(spy:arg(1)).falsy()
        k:Show()
        expect(spy:arg(1)).truthy()
        expect(spy.count).eq(2)
        expect(k:IsShown()).truthy()
    end)

    it("stops capturing on Destroy", function()
        local k = H.C.KeyCapture({}, host)
        H.click(k)
        k:Destroy()
        expect(k._capturing).falsy()
        expect(k._catcher:IsKeyboardEnabled()).falsy()
    end)
end)

describe("Components.ColorPicker", function()
    local host
    -- Internal layout constants
    local SV_SIZE, BAR_W = 120, 185

    before_each(function()
        H.setup()
        host = H.parent(400, 300)
    end)

    local function picker(props)
        return H.mount(H.C.ColorPicker(props or {}, host))
    end

    describe("construction", function()
        it("is 240x180", function()
            H.expectSize(picker(), 240, 180)
        end)

        it("defaults to opaque white", function()
            expect({ picker():GetValue() }).deepEq({ 1, 1, 1, 1 })
        end)

        it("adopts the given colour", function()
            expect({ picker({ value = { 0.2, 0.4, 0.6, 0.8 } }):GetValue() })
                .deepEq({ 0.2, 0.4, 0.6, 0.8 }, 0.0001)
        end)

        it("defaults a missing alpha to 1", function()
            local _, _, _, a = picker({ value = { 1, 0, 0 } }):GetValue()
            expect(a).eq(1)
        end)

        it("shows the colour in the preview swatch", function()
            local p = picker({ value = { 1, 0, 0, 1 } })
            expect({ p._preview:GetColorTexture() }).deepEq({ 1, 0, 0, 1 })
        end)

        it("seeds the hex field from the colour", function()
            expect(picker({ value = { 1, 0, 0, 1 } })._hexInput:GetValue()).eq("FF0000FF")
        end)

        it("keeps the saturation square square", function()
            H.expectSize(picker()._svFrame, SV_SIZE, SV_SIZE)
        end)

        it("gives both bars the same width", function()
            local p = picker()
            H.expectSize(p._hueFrame, BAR_W, 14)
            H.expectSize(p._alphaFrame, BAR_W, 14)
        end)

        it("keeps every part inside the panel", function()
            local p = picker()
            for _, part in ipairs({ p._svFrame, p._hueFrame, p._alphaFrame, p._preview }) do
                H.expectInside(part, p:GetFrame())
            end
        end)

        it("gives the hex field room beside the preview without overlap", function()
            local p = picker()
            H.expectNoOverlap({ p._preview, p._hexInput })
        end)

        it("uses the alt surface and border tokens for the panel", function()
            local p = picker()
            H.expectTokenColor(H.backdropColor(p), "colorBgAlt")
            H.expectTokenColor(H.borderColor(p), "colorBorder")
        end)

        it("derives the backdrop insets from the borderWidth token", function()
            local p = picker()
            local bw = H.token("borderWidth")
            expect(p:GetFrame():GetBackdrop().edgeSize).eq(bw)
            expect(p:GetFrame():GetBackdrop().insets)
                .deepEq({ left = bw, right = bw, top = bw, bottom = bw })
        end)

        it("follows the borderWidth token when the theme changes it", function()
            local p = picker()
            H.T:CreateUserTheme("Thick", "Modern")
            H.T:SetUserToken("Thick", "borderWidth", 3)
            H.T:SetActive("Thick")
            expect(p:GetFrame():GetBackdrop().edgeSize).eq(3)
        end)

        it("keeps the standard accessors", function()
            local p = picker()
            expect(p:GetFrame()).eq(p._f)
            expect(p:GetWidth()).eq(240)
            expect(p:GetHeight()).eq(180)
            expect(p:IsShown()).truthy()
        end)

        it("emits SIZE_CHANGED from an explicit SetSize", function()
            local p = picker()
            local spy = H.signalSpy(p, H.S.SIGNALS.SIZE_CHANGED)
            p:SetSize(300, 220)
            H.expectSize(p, 300, 220)
            expect(spy.count).eq(1)
            expect(spy:arg(1)).eq(300)
        end)
    end)

    describe("thumb placement", function()
        it("puts the saturation thumb at the fully saturated right edge for pure red", function()
            local p = picker({ value = { 1, 0, 0, 1 } })
            local svBox = H.box(p._svFrame)
            local thumb = H.box(p._svThumb)
            expect(thumb.left + thumb.width / 2).near(svBox.left + SV_SIZE, 0.5)
        end)

        it("puts the saturation thumb at the unsaturated left edge for grey", function()
            local p = picker({ value = { 0.5, 0.5, 0.5, 1 } })
            local svBox = H.box(p._svFrame)
            local thumb = H.box(p._svThumb)
            expect(thumb.left + thumb.width / 2).near(svBox.left, 0.5)
        end)

        it("puts the thumb at the bright top edge for a full-value colour", function()
            local p = picker({ value = { 1, 0, 0, 1 } })
            local svBox = H.box(p._svFrame)
            local thumb = H.box(p._svThumb)
            expect(thumb.top + thumb.height / 2).near(svBox.top, 0.5)
        end)

        it("puts the thumb at the black bottom edge for black", function()
            local p = picker({ value = { 0, 0, 0, 1 } })
            local svBox = H.box(p._svFrame)
            local thumb = H.box(p._svThumb)
            expect(thumb.left + thumb.width / 2).near(svBox.left, 0.5)
            expect(thumb.top + thumb.height / 2).near(svBox.top + SV_SIZE, 0.5)
        end)

        it("shades the square black along the bottom edge", function()
            -- A VERTICAL gradient runs its first colour along the bottom, so the opaque
            -- black stop must come first for the square to be bright at the top.
            local p = picker()
            local grad = p._svLayers:GetChildren()[3].GetGradient
                and p._svLayers:GetChildren()[3]:GetGradient()
            expect(grad).notNil()
            expect(grad.orientation).eq("VERTICAL")
            expect(grad.from.a).as("bottom stop is opaque black").eq(1)
            expect(grad.to.a).as("top stop is transparent").eq(0)
        end)

        it("puts the thumb where the user clicked (round trip)", function()
            local p = picker({ value = { 1, 0, 0, 1 } })
            local sv = H.box(p._svFrame)
            local clickX = sv.left + SV_SIZE * 0.5
            local clickY = sv.top + SV_SIZE * 0.25
            H.cursor(clickX, H.state.screenHeight - clickY)
            H.mouseDown(p._svFrame, "LeftButton")
            local thumb = H.box(p._svThumb)
            expect(thumb.left + thumb.width / 2).near(clickX, 1)
            expect(thumb.top + thumb.height / 2).near(clickY, 1)
        end)

        it("round trips every corner of the square", function()
            local p = picker({ value = { 1, 0, 0, 1 } })
            local sv = H.box(p._svFrame)
            for _, corner in ipairs({ { 0, 0 }, { 1, 0 }, { 0, 1 }, { 1, 1 }, { 0.5, 0.5 } }) do
                local clickX = sv.left + SV_SIZE * corner[1]
                local clickY = sv.top + SV_SIZE * corner[2]
                H.cursor(clickX, H.state.screenHeight - clickY)
                H.mouseDown(p._svFrame, "LeftButton")
                H.mouseUp(p._svFrame, "LeftButton")
                local thumb = H.box(p._svThumb)
                expect(thumb.left + thumb.width / 2)
                    .as("x at " .. corner[1] .. "," .. corner[2]).near(clickX, 1)
                expect(thumb.top + thumb.height / 2)
                    .as("y at " .. corner[1] .. "," .. corner[2]).near(clickY, 1)
            end
        end)

        it("puts the hue thumb at the left for hue zero", function()
            local p = picker({ value = { 1, 0, 0, 1 } })
            local bar, thumb = H.box(p._hueFrame), H.box(p._hueThumb)
            expect(thumb.left + thumb.width / 2).near(bar.left, 0.5)
        end)

        it("moves the hue thumb a third along for green", function()
            local p = picker({ value = { 0, 1, 0, 1 } })
            local bar, thumb = H.box(p._hueFrame), H.box(p._hueThumb)
            expect(thumb.left + thumb.width / 2).near(bar.left + BAR_W / 3, 1)
        end)

        it("puts the alpha thumb at the right for full opacity", function()
            local p = picker({ value = { 1, 1, 1, 1 } })
            local bar, thumb = H.box(p._alphaFrame), H.box(p._alphaThumb)
            expect(thumb.left + thumb.width / 2).near(bar.left + BAR_W, 0.5)
        end)

        it("puts the alpha thumb at the left for zero opacity", function()
            local p = picker({ value = { 1, 1, 1, 0 } })
            local bar, thumb = H.box(p._alphaFrame), H.box(p._alphaThumb)
            expect(thumb.left + thumb.width / 2).near(bar.left, 0.5)
        end)

        it("repositions every thumb on SetValue", function()
            local p = picker({ value = { 1, 0, 0, 1 } })
            p:SetValue(0, 0, 1, 0.5)
            local bar, hueThumb = H.box(p._hueFrame), H.box(p._hueThumb)
            expect(hueThumb.left + hueThumb.width / 2).near(bar.left + BAR_W * (2 / 3), 1)
            local abar, aThumb = H.box(p._alphaFrame), H.box(p._alphaThumb)
            expect(aThumb.left + aThumb.width / 2).near(abar.left + BAR_W * 0.5, 1)
        end)

        it("sizes the bar thumbs from the sizeControlSm token", function()
            local p = picker()
            H.expectSize(p._hueThumb, nil, H.token("sizeControlSm"))
            H.expectSize(p._alphaThumb, nil, H.token("sizeControlSm"))
        end)

        it("re-heights the bar thumbs when the sizeControlSm token changes", function()
            local p = picker({ value = { 0, 1, 0, 1 } })
            local before = H.box(p._hueThumb)
            H.T:CreateUserTheme("Tall", "Modern")
            H.T:SetUserToken("Tall", "sizeControlSm", 26)
            H.T:SetActive("Tall")
            H.expectSize(p._hueThumb, nil, 26)
            H.expectSize(p._alphaThumb, nil, 26)
            expect(H.box(p._hueThumb).left)
                .as("re-heighting must not move the thumb off its hue").near(before.left, 0.5)
        end)

        it("tints the saturation square with the current hue at full value", function()
            local p = picker({ value = { 0, 1, 0, 1 } })
            expect({ p._svHueTex:GetColorTexture() }).deepEq({ 0, 1, 0, 1 }, 0.0001)
        end)
    end)

    describe("SetValue", function()
        it("does not emit VALUE_CHANGED", function()
            local p = picker()
            local spy = H.signalSpy(p, H.S.SIGNALS.VALUE_CHANGED)
            p:SetValue(0, 1, 0, 1)
            expect(spy.count).eq(0)
        end)

        it("refreshes the preview and the hex field", function()
            local p = picker()
            p:SetValue(0, 0, 1, 1)
            expect({ p._preview:GetColorTexture() }).deepEq({ 0, 0, 1, 1 })
            expect(p._hexInput:GetValue()).eq("0000FFFF")
        end)

        it("defaults missing components to 1", function()
            local p = picker({ value = { 0, 0, 0, 0 } })
            p:SetValue()
            expect({ p:GetValue() }).deepEq({ 1, 1, 1, 1 })
        end)
    end)

    describe("picking with the mouse", function()
        it("sets saturation and value from a click in the square", function()
            local p = picker({ value = { 1, 0, 0, 1 } })
            local sv = H.box(p._svFrame)
            H.cursor(sv.left + SV_SIZE / 2, H.state.screenHeight - (sv.top + SV_SIZE / 2))
            H.mouseDown(p._svFrame, "LeftButton")
            local r, g, b = p:GetValue()
            expect(r).near(0.5, 0.02)
            expect(g).near(0.25, 0.02)
            expect(b).near(0.25, 0.02)
        end)

        it("reads full brightness at the top edge and black at the bottom", function()
            local p = picker({ value = { 1, 0, 0, 1 } })
            local sv = H.box(p._svFrame)
            H.cursor(sv.left + SV_SIZE, H.state.screenHeight - sv.top)
            H.mouseDown(p._svFrame, "LeftButton")
            expect(select(1, p:GetValue())).as("top edge is fully bright").near(1, 0.02)
            H.mouseUp(p._svFrame, "LeftButton")

            H.cursor(sv.left + SV_SIZE, H.state.screenHeight - (sv.top + SV_SIZE))
            H.mouseDown(p._svFrame, "LeftButton")
            local r, g, b = p:GetValue()
            expect(r + g + b).as("bottom edge is black").near(0, 0.02)
        end)

        it("emits VALUE_CHANGED as a table and COLOR_PICKED as components", function()
            local p = picker({ value = { 1, 0, 0, 1 } })
            local changed = H.signalSpy(p, H.S.SIGNALS.VALUE_CHANGED)
            local picked  = H.signalSpy(p, H.C.COLORPICKER_SIGNALS.COLOR_PICKED)
            local sv = H.box(p._svFrame)
            H.cursor(sv.left + 10, H.state.screenHeight - (sv.top + 10))
            H.mouseDown(p._svFrame, "LeftButton")
            expect(changed.count).gte(1)
            expect(type(changed:arg(1))).as("VALUE_CHANGED carries one table here").eq("table")
            expect(picked.last.n).as("COLOR_PICKED carries r,g,b,a").eq(4)
        end)

        it("calls onChange with four components", function()
            local seen
            local p = picker({ value = { 1, 0, 0, 1 },
                               onChange = function(r, g, b, a) seen = { r, g, b, a } end })
            local sv = H.box(p._svFrame)
            H.cursor(sv.left + 10, H.state.screenHeight - (sv.top + 10))
            H.mouseDown(p._svFrame, "LeftButton")
            expect(#seen).eq(4)
        end)

        it("clamps a click outside the square", function()
            local p = picker({ value = { 1, 0, 0, 1 } })
            local sv = H.box(p._svFrame)
            H.cursor(sv.left - 500, H.state.screenHeight - (sv.top - 500))
            H.mouseDown(p._svFrame, "LeftButton")
            local r, g, b = p:GetValue()
            for _, c in ipairs({ r, g, b }) do
                expect(c).between(0, 1)
            end
        end)

        it("sets the hue from a click in the hue bar", function()
            local p = picker({ value = { 1, 0, 0, 1 } })
            local bar = H.box(p._hueFrame)
            H.cursor(bar.left + BAR_W / 3, H.state.screenHeight - (bar.top + 7))
            H.mouseDown(p._hueFrame, "LeftButton")
            local r, g, b = p:GetValue()
            expect(g).as("a third along the bar is green").gt(r)
            expect(g).gt(b)
        end)

        it("sets alpha from a click in the alpha bar", function()
            local p = picker({ value = { 1, 1, 1, 1 } })
            local bar = H.box(p._alphaFrame)
            H.cursor(bar.left + BAR_W * 0.25, H.state.screenHeight - (bar.top + 7))
            H.mouseDown(p._alphaFrame, "LeftButton")
            local _, _, _, a = p:GetValue()
            expect(a).near(0.25, 0.02)
        end)

        it("keeps tracking the cursor while held and stops on release", function()
            local p = picker({ value = { 1, 1, 1, 1 } })
            local bar = H.box(p._alphaFrame)
            H.cursor(bar.left, H.state.screenHeight - (bar.top + 7))
            H.mouseDown(p._alphaFrame, "LeftButton")
            H.cursor(bar.left + BAR_W, H.state.screenHeight - (bar.top + 7))
            H.tick(0.05)
            expect(select(4, p:GetValue())).eq(1)

            H.mouseUp(p._alphaFrame, "LeftButton")
            H.cursor(bar.left, H.state.screenHeight - (bar.top + 7))
            H.tick(0.05)
            expect(select(4, p:GetValue())).as("no idle tracking after release").eq(1)
        end)

        it("stops tracking when hidden", function()
            local p = picker({ value = { 1, 1, 1, 1 } })
            H.mouseDown(p._alphaFrame, "LeftButton")
            p:Hide()
            expect(p:GetFrame():GetScript("OnUpdate")).isNil()
        end)
    end)

    describe("hex entry", function()
        local function submitHex(p, hex)
            p._hexInput:SetValue(hex)
            H.pressEnter(p._hexInput)
        end

        it("accepts eight hex digits", function()
            local p = picker()
            submitHex(p, "FF8000CC")
            local r, g, b, a = p:GetValue()
            expect(r).near(1, 0.01)
            expect(g).near(0x80 / 255, 0.01)
            expect(b).eq(0)
            expect(a).near(0xCC / 255, 0.01)
        end)

        it("assumes full opacity for six digits", function()
            local p = picker({ value = { 0, 0, 0, 0 } })
            submitHex(p, "00FF00")
            expect(select(4, p:GetValue())).eq(1)
        end)

        it("accepts a leading hash", function()
            local p = picker()
            submitHex(p, "#0000FF")
            local r, g, b = p:GetValue()
            expect(b).eq(1)
            expect(r).eq(0)
            expect(g).eq(0)
        end)

        it("ignores a malformed value", function()
            local p = picker({ value = { 1, 0, 0, 1 } })
            submitHex(p, "not a colour")
            expect({ p:GetValue() }).deepEq({ 1, 0, 0, 1 })
        end)

        it("ignores a hex string of the wrong length", function()
            local p = picker({ value = { 1, 0, 0, 1 } })
            submitHex(p, "ABCD")
