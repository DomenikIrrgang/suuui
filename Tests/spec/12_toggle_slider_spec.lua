local H = require("harness")

describe("Components.Toggle", function()
    local host
    before_each(function()
        H.setup()
        host = H.parent(200, 100)
    end)

    -- The knob is inset 3px on the off side and sized to the track height minus 4.
    local function knobSize(t) return t:GetHeight() - 4 end
    local function onOffset(t)  return t:GetWidth() - knobSize(t) - 3 end

    describe("sizing", function()
        it("takes its size from the toggle and control-small tokens", function()
            local t = H.C.Toggle({}, host)
            H.expectSize(t, H.token("sizeToggleW"), H.token("sizeControlSm"))
        end)

        it("is not floored against the font size, having no text of its own", function()
            local t = H.C.Toggle({}, host)
            H.T:CreateUserTheme("Big", "Modern")
            H.T:SetUserToken("Big", "fontSizeMd", 40)
            H.T:SetActive("Big")
            H.expectSize(t, H.token("sizeToggleW"), H.token("sizeControlSm"))
        end)

        it("tracks both size tokens when they change", function()
            local t = H.C.Toggle({}, host)
            H.T:CreateUserTheme("Wide", "Modern")
            H.T:SetUserToken("Wide", "sizeToggleW", 60)
            H.T:SetUserToken("Wide", "sizeControlSm", 26)
            H.T:SetActive("Wide")
            H.expectSize(t, 60, 26)
        end)

        it("stops tracking tokens once both dimensions are given", function()
            local t = H.C.Toggle({ w = 50, h = 20 }, host)
            H.T:CreateUserTheme("Wide", "Modern")
            H.T:SetUserToken("Wide", "sizeToggleW", 90)
            H.T:SetActive("Wide")
            H.expectSize(t, 50, 20)
        end)

        it("keeps tracking tokens if only one dimension is given", function()
            local t = H.C.Toggle({ w = 50 }, host)
            expect(t._autoSize).falsy()
            H.expectSize(t, 50, H.token("sizeControlSm"))
        end)

        it("drops token sizing after SetSize", function()
            local t = H.C.Toggle({}, host)
            t:SetSize(80, 30)
            H.T:CreateUserTheme("Wide", "Modern")
            H.T:SetUserToken("Wide", "sizeToggleW", 90)
            H.T:SetActive("Wide")
            H.expectSize(t, 80, 30)
        end)
    end)

    describe("knob placement", function()
        it("parks the knob 3px from the left when off", function()
            local t = H.mount(H.C.Toggle({ value = false }, host))
            H.expectSize(t._knob, knobSize(t), knobSize(t))
            H.expectOffset(t._knob, t:GetFrame(), 3, nil)
            H.expectCenteredV(t._knob, t:GetFrame())
        end)

        it("parks the knob 3px from the right when on", function()
            local t = H.mount(H.C.Toggle({ value = true }, host))
            H.expectOffset(t._knob, t:GetFrame(), onOffset(t), nil)
            local tb, kb = H.box(t), H.box(t._knob)
            expect(kb.right).eq(tb.right - 3)
        end)

        it("keeps the knob inside the track at both extremes", function()
            local off = H.mount(H.C.Toggle({ value = false }, host))
            local on  = H.mount(H.C.Toggle({ value = true }, H.parent(200, 100)))
            H.expectInside(off._knob, off:GetFrame())
            H.expectInside(on._knob, on:GetFrame())
        end)

        it("animates the knob across on a value change", function()
            local t = H.mount(H.C.Toggle({ value = false }, host))
            H.click(t)
            H.runAnimations()
            H.expectOffset(t._knob, t:GetFrame(), onOffset(t), nil)
        end)

        it("snaps the knob without animating when the frame is resized", function()
            local col = H.Layout:CreateContainer({ parent = host, layout = "flow",
                                                   dir = "horizontal" })
            local t = H.C.Toggle({ value = true }, col:GetFrame())
            col:Add(t, { width = 80, height = 24 })
            -- No animation ticks: a resize must place the knob immediately
            H.expectOffset(t._knob, t:GetFrame(), 80 - 20 - 3, nil)
        end)

        it("recomputes the knob size from a new height", function()
            local t = H.mount(H.C.Toggle({}, host))
            t:SetSize(60, 30)
            H.expectSize(t._knob, 26, 26)
        end)
    end)

    describe("value", function()
        it("defaults to off", function()
            expect(H.C.Toggle({}, host):GetValue()).falsy()
        end)

        it("coerces a truthy non-boolean to off", function()
            expect(H.C.Toggle({ value = "yes" }, host):GetValue()).as("only true counts").falsy()
        end)

        it("flips on click and emits VALUE_CHANGED with new and old", function()
            local t = H.C.Toggle({ value = false }, host)
            local spy = H.signalSpy(t, H.S.SIGNALS.VALUE_CHANGED)
            H.click(t)
            expect(t:GetValue()).truthy()
            expect(spy:arg(1)).truthy()
            expect(spy:arg(2)).falsy()
            H.click(t)
            expect(t:GetValue()).falsy()
            expect(spy.count).eq(2)
        end)

        it("calls onChange with the new value", function()
            local seen
            local t = H.C.Toggle({ value = false, onChange = function(v) seen = v end }, host)
            H.click(t)
            expect(seen).truthy()
        end)

        it("sets the value silently with SetValue", function()
            local t = H.C.Toggle({}, host)
            local spy = H.signalSpy(t, H.S.SIGNALS.VALUE_CHANGED)
            t:SetValue(true)
            expect(t:GetValue()).truthy()
            expect(spy.count).as("setters do not emit").eq(0)
        end)

        it("coerces SetValue to a boolean", function()
            local t = H.C.Toggle({}, host)
            t:SetValue("truthy string")
            expect(t:GetValue()).falsy()
            t:SetValue(true)
            expect(t:GetValue()).truthy()
        end)
    end)

    describe("theming and state", function()
        it("shows the accent surface when on and the alt surface when off", function()
            local t = H.C.Toggle({ value = true }, host)
            H.expectTokenColor({ t._track:GetBackdropColor() }, "colorAccent")
            t:SetValue(false)
            H.expectTokenColor({ t._track:GetBackdropColor() }, "colorBgAlt")
        end)

        it("uses a white knob when enabled and the disabled text colour when not", function()
            local t = H.C.Toggle({}, host)
            expect({ t._knob:GetBackdropColor() }).deepEq({ 1, 1, 1, 1 })
            t:SetEnabled(false)
            H.expectTokenColor({ t._knob:GetBackdropColor() }, "colorTextDisabled")
        end)

        it("stops responding to clicks when disabled", function()
            local t = H.C.Toggle({ value = false }, host)
            t:SetEnabled(false)
            expect(H.click(t)).falsy()
            H.forceClick(t)
            expect(t:GetValue()).as("internal guard also holds").falsy()
        end)

        it("emits ENABLED_CHANGED", function()
            local t = H.C.Toggle({}, host)
            local spy = H.signalSpy(t, H.S.SIGNALS.ENABLED_CHANGED)
            t:SetEnabled(false)
            expect(spy:arg(1)).falsy()
        end)

        it("emits MOUSE_ENTER and MOUSE_LEAVE", function()
            local t = H.C.Toggle({}, host)
            local enter = H.signalSpy(t, H.S.SIGNALS.MOUSE_ENTER)
            H.hover(t)
            H.unhover(t)
            expect(enter.count).eq(1)
        end)

        it("emits SIZE_CHANGED when a layout resizes it", function()
            local col = H.Layout:CreateContainer({ parent = host, layout = "flow" })
            local t = H.C.Toggle({}, col:GetFrame())
            local spy = H.signalSpy(t, H.S.SIGNALS.SIZE_CHANGED)
            col:Add(t, { width = 70, height = 30 })
            expect(spy.count).gte(1)
        end)
    end)
end)

describe("Components.Slider", function()
    local host
    before_each(function()
        H.setup()
        host = H.parent(300, 200)
    end)

    -- Layout constants inside Slider.lua
    local TRACK_PAD, THUMB, TRACK_AREA, LABEL_MIN_H = 6, 12, 22, 14

    local function trackWidth(s) return s:GetWidth() - TRACK_PAD * 2 end

    describe("sizing", function()
        it("defaults to 200 wide", function()
            local s = H.C.Slider({}, host)
            H.expectSize(s, 200, nil)
        end)

        it("reserves a label strip measured from the font plus the track area", function()
            local s = H.C.Slider({ label = "Scale" }, host)
            local expected = math.max(LABEL_MIN_H, H.lineHeight(H.token("fontSizeMd"))) + TRACK_AREA
            H.expectSize(s, nil, expected)
        end)

        it("keeps the minimum label strip for an empty label", function()
            local s = H.C.Slider({}, host)
            H.expectSize(s, nil, LABEL_MIN_H + TRACK_AREA)
        end)

        it("grows taller when the font size token grows", function()
            local s = H.C.Slider({ label = "Scale" }, host)
            local before = s:GetHeight()
            H.T:CreateUserTheme("Big", "Modern")
            H.T:SetUserToken("Big", "fontSizeMd", 30)
            H.T:SetActive("Big")
            expect(s:GetHeight()).gt(before)
            H.expectSize(s, nil, H.lineHeight(30) + TRACK_AREA)
        end)

        it("emits SIZE_CHANGED when the label strip re-heights it", function()
            local s = H.C.Slider({ label = "Scale" }, host)
            local spy = H.signalSpy(s, H.S.SIGNALS.SIZE_CHANGED)
            H.T:CreateUserTheme("Big", "Modern")
            H.T:SetUserToken("Big", "fontSizeMd", 30)
            H.T:SetActive("Big")
            expect(spy.count).gte(1)
        end)
    end)

    describe("value clamping", function()
        it("clamps an out-of-range initial value up to min", function()
            expect(H.C.Slider({ min = 10, max = 20, value = -5 }, host):GetValue()).eq(10)
        end)

        it("clamps an out-of-range initial value down to max", function()
            expect(H.C.Slider({ min = 10, max = 20, value = 99 }, host):GetValue()).eq(20)
        end)

        it("defaults the value to min", function()
            expect(H.C.Slider({ min = 7, max = 9 }, host):GetValue()).eq(7)
        end)

        it("defaults the range to 0..100", function()
            local s = H.C.Slider({ value = 50 }, host)
            s:SetValue(1000)
            expect(s:GetValue()).eq(100)
            s:SetValue(-1000)
            expect(s:GetValue()).eq(0)
        end)

        it("does not emit VALUE_CHANGED from SetValue", function()
            local s = H.C.Slider({}, host)
            local spy = H.signalSpy(s, H.S.SIGNALS.VALUE_CHANGED)
            s:SetValue(42)
            expect(spy.count).eq(0)
        end)
    end)

    describe("fill and thumb geometry", function()
        it("shows a 1px fill at the minimum", function()
            local s = H.mount(H.C.Slider({ min = 0, max = 100, value = 0, w = 200 }, host))
            expect(s._fill:GetWidth()).eq(1)
        end)

        it("fills the whole track at the maximum", function()
            local s = H.mount(H.C.Slider({ min = 0, max = 100, value = 100, w = 200 }, host))
            expect(s._fill:GetWidth()).eq(trackWidth(s))
        end)

        it("fills proportionally in between", function()
            local s = H.mount(H.C.Slider({ min = 0, max = 100, value = 25, w = 200 }, host))
            expect(s._fill:GetWidth()).eq(trackWidth(s) * 0.25)
        end)

        it("centres the thumb on the fill edge", function()
            local s = H.mount(H.C.Slider({ min = 0, max = 100, value = 50, w = 200 }, host))
            local tb = H.box(s._track)
            local thumb = H.box(s._thumb)
            expect(thumb.left + thumb.width / 2).near(tb.left + trackWidth(s) * 0.5, 0.5)
        end)

        it("keeps the thumb size constant", function()
            local s = H.mount(H.C.Slider({ value = 50, w = 200 }, host))
            H.expectSize(s._thumb, THUMB, THUMB)
        end)

        it("insets the track by the track padding on both sides", function()
            local s = H.mount(H.C.Slider({ w = 200 }, host))
            H.expectSize(s._track, 200 - TRACK_PAD * 2, 4)
            local sb, tb = H.box(s), H.box(s._track)
            expect(tb.left).eq(sb.left + TRACK_PAD)
            expect(tb.right).eq(sb.right - TRACK_PAD)
        end)

        it("re-renders the fill when a parent layout widens it", function()
            local col = H.Layout:CreateContainer({ parent = host, layout = "flow",
                                                   dir = "vertical" })
            local s = H.C.Slider({ min = 0, max = 100, value = 50 }, col:GetFrame())
            col:Add(s, { width = "fill" })
            expect(s._fill:GetWidth()).eq((300 - TRACK_PAD * 2) * 0.5)
        end)

        it("keeps the thumb within the track bounds at both extremes", function()
            for _, value in ipairs({ 0, 100 }) do
                local parent = H.parent(300, 100)
                local s = H.mount(H.C.Slider({ min = 0, max = 100, value = value, w = 200 }, parent))
                local thumb, sliderBox = H.box(s._thumb), H.box(s)
                expect(thumb.left).as("thumb stays on screen").gte(sliderBox.left - 1)
                expect(thumb.right).lte(sliderBox.right + 1)
            end
        end)
    end)

    describe("value display", function()
        it("shows a whole number when the step is 1 or larger", function()
            local s = H.C.Slider({ min = 0, max = 10, value = 4, step = 1 }, host)
            expect(s._valText:GetText()).eq("4")
        end)

        it("floors the display for integral steps", function()
            local s = H.C.Slider({ min = 0, max = 10, step = 2 }, host)
            s:SetValue(7.9)
            expect(s._valText:GetText()).eq("7")
        end)

        it("shows the raw value for fractional steps", function()
            local s = H.C.Slider({ min = 0, max = 1, value = 0.25, step = 0.05 }, host)
            expect(s._valText:GetText()).eq("0.25")
        end)
    end)

    describe("dragging", function()
        local function dragTo(s, fraction)
            local tb = H.box(s._track)
            H.cursor(tb.left + tb.width * fraction, tb.top)
            H.mouseDown(s._hit, "LeftButton")
        end

        it("sets the value from the cursor position on mouse down", function()
            local s = H.mount(H.C.Slider({ min = 0, max = 100, value = 0, w = 200, step = 1 }, host))
            dragTo(s, 0.5)
            expect(s:GetValue()).near(50, 1)
        end)

        it("emits VALUE_CHANGED with new and old", function()
            local s = H.mount(H.C.Slider({ min = 0, max = 100, value = 0, w = 200, step = 1 }, host))
            local spy = H.signalSpy(s, H.S.SIGNALS.VALUE_CHANGED)
            dragTo(s, 0.75)
            expect(spy.count).gte(1)
            expect(spy:arg(1)).near(75, 1)
            expect(spy:arg(2)).eq(0)
        end)

        it("calls onChange while dragging", function()
            local seen = {}
            local s = H.mount(H.C.Slider({ min = 0, max = 100, value = 0, w = 200, step = 1,
                                           onChange = function(v) seen[#seen + 1] = v end }, host))
            dragTo(s, 0.2)
            H.tick(0.05)
            expect(#seen).gte(1)
        end)

        it("snaps to the step", function()
            local s = H.mount(H.C.Slider({ min = 0, max = 100, value = 0, w = 200, step = 25 }, host))
            dragTo(s, 0.4)
            expect(s:GetValue() % 25).eq(0)
        end)

        it("clamps to the range when the cursor leaves the track", function()
            local s = H.mount(H.C.Slider({ min = 0, max = 100, value = 50, w = 200, step = 1 }, host))
            local tb = H.box(s._track)
            H.cursor(tb.left - 500, tb.top)
            H.mouseDown(s._hit, "LeftButton")
            expect(s:GetValue()).eq(0)
            H.cursor(tb.left + 5000, tb.top)
            H.tick(0.05)
            expect(s:GetValue()).eq(100)
        end)

        it("keeps tracking the cursor across ticks while held", function()
            local s = H.mount(H.C.Slider({ min = 0, max = 100, value = 0, w = 200, step = 1 }, host))
            local tb = H.box(s._track)
            H.cursor(tb.left, tb.top)
            H.mouseDown(s._hit, "LeftButton")
            H.cursor(tb.left + tb.width, tb.top)
            H.tick(0.05)
            expect(s:GetValue()).eq(100)
        end)

        it("stops tracking on mouse up", function()
            local s = H.mount(H.C.Slider({ min = 0, max = 100, value = 0, w = 200, step = 1 }, host))
            local tb = H.box(s._track)
            H.cursor(tb.left, tb.top)
            H.mouseDown(s._hit, "LeftButton")
            H.mouseUp(s._hit, "LeftButton")
            H.cursor(tb.left + tb.width, tb.top)
            H.tick(0.05)
            expect(s:GetValue()).as("no idle OnUpdate after release").eq(0)
        end)

        it("ignores non-left mouse buttons", function()
            local s = H.mount(H.C.Slider({ min = 0, max = 100, value = 0, w = 200, step = 1 }, host))
            local tb = H.box(s._track)
            H.cursor(tb.left + tb.width, tb.top)
            H.mouseDown(s._hit, "RightButton")
            expect(s:GetValue()).eq(0)
        end)

        it("ignores dragging while disabled", function()
            local s = H.mount(H.C.Slider({ min = 0, max = 100, value = 0, w = 200, step = 1 }, host))
            s:SetEnabled(false)
            local tb = H.box(s._track)
            H.cursor(tb.left + tb.width, tb.top)
            expect(H.mouseDown(s._hit, "LeftButton")).falsy()
            expect(s:GetValue()).eq(0)
        end)

        it("does not emit when the snapped value has not moved", function()
            local s = H.mount(H.C.Slider({ min = 0, max = 100, value = 50, w = 200, step = 1 }, host))
            local tb = H.box(s._track)
            H.cursor(tb.left + tb.width * 0.5, tb.top)
            local spy = H.signalSpy(s, H.S.SIGNALS.VALUE_CHANGED)
            H.mouseDown(s._hit, "LeftButton")
            H.tick(0.05)
            H.tick(0.05)
            expect(spy.count).eq(0)
        end)
    end)

    describe("theming", function()
        it("colours the fill and thumb dot with the accent token", function()
            local s = H.C.Slider({ value = 50 }, host)
            H.expectTokenColor({ s._fill:GetColorTexture() }, "colorAccent")
            H.expectTokenColor({ s._thumbDot:GetVertexColor() }, "colorAccent")
        end)

        it("rings the thumb with the border token", function()
            local s = H.C.Slider({ value = 50 }, host)
            H.expectTokenColor({ s._thumbRing:GetVertexColor() }, "colorBorder")
        end)

        it("colours the track background with the alt surface", function()
            local s = H.C.Slider({ value = 50 }, host)
            H.expectTokenColor({ s._trackBg:GetColorTexture() }, "colorBgAlt")
        end)

        it("uses the medium font for both label and value", function()
            local s = H.C.Slider({ label = "Scale" }, host)
            local _, labelSize = s._labelText:GetFont()
            local _, valSize = s._valText:GetFont()
            expect(labelSize).eq(H.token("fontSizeMd"))
            expect(valSize).eq(H.token("fontSizeMd"))
        end)

        it("puts the label left and the value right on the same row", function()
            local s = H.mount(H.C.Slider({ label = "Scale", value = 5, w = 200 }, host))
            local lb, vb = H.box(s._labelText), H.box(s._valText)
            expect(lb.left).lte(vb.left)
            expect(vb.right).near(H.box(s).right, 0.5)
            expect(s._valText:GetJustifyH()).eq("RIGHT")
        end)

        it("unregisters its drag ticker on Destroy", function()
            local s = H.mount(H.C.Slider({ value = 0, w = 200, step = 1 }, host))
            H.mouseDown(s._hit, "LeftButton")
            s:Destroy()
            expect(s:GetFrame():GetScript("OnUpdate")).isNil()
        end)
    end)
end)
