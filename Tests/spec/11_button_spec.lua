local H = require("harness")

-- The button hugs its label: width = measured text + 2px slack + 2 * padX, where
-- padX is spaceSm + borderWidth. Computing it from tokens keeps the expectation
-- valid when the theme changes rather than baking in one theme's numbers.
local function expectedWidth(label, minW)
    local size = H.token("fontSizeMd")
    local padX = H.token("spaceSm") + H.token("borderWidth")
    return math.max(H.textWidth(label, size) + 2 + padX * 2, minW or 0)
end

local function expectedHeight(minH)
    local size = H.token("fontSizeMd")
    local padY = H.token("spaceXs") + H.token("borderWidth")
    return math.max(H.lineHeight(size) + padY * 2, minH or 0)
end

describe("Components.Button", function()
    local host
    before_each(function()
        H.setup()
        host = H.parent(400, 200)
    end)

    describe("auto-sizing", function()
        it("hugs its label on both axes", function()
            local b = H.C.Button({ label = "Apply" }, host)
            H.expectSize(b, expectedWidth("Apply"), expectedHeight())
        end)

        it("grows wider for a longer label", function()
            local short = H.C.Button({ label = "OK" }, host)
            local long  = H.C.Button({ label = "Reset every setting" }, host)
            expect(long:GetWidth()).gt(short:GetWidth())
            H.expectSize(long, expectedWidth("Reset every setting"), nil)
        end)

        it("respects minW as a floor, not a fixed width", function()
            local b = H.C.Button({ label = "X", minW = 120 }, host)
            H.expectSize(b, 120, nil)
            local wide = H.C.Button({ label = string.rep("wide ", 12), minW = 120 }, host)
            expect(wide:GetWidth()).gt(120)
        end)

        it("respects minH as a floor", function()
            local b = H.C.Button({ label = "X", minH = 60 }, host)
            H.expectSize(b, nil, 60)
        end)

        it("stops auto-sizing on the axes the caller pinned", function()
            local b = H.C.Button({ label = "Fixed", w = 200, h = 40 }, host)
            H.expectSize(b, 200, 40)
            b:SetLabel("A different much longer label")
            H.expectSize(b, 200, 40)
        end)

        it("keeps hugging the other axis when only one is pinned", function()
            local b = H.C.Button({ label = "Half", w = 200 }, host)
            H.expectSize(b, 200, expectedHeight())
        end)

        it("drops auto-sizing entirely after SetSize", function()
            local b = H.C.Button({ label = "Auto" }, host)
            b:SetSize(90, 30)
            b:SetLabel("Something considerably longer")
            H.expectSize(b, 90, 30)
        end)

        it("re-fits and reports a new size when SetLabel widens it", function()
            local b = H.C.Button({ label = "A" }, host)
            local spy = H.signalSpy(b, H.S.SIGNALS.SIZE_CHANGED)
            b:SetLabel("A far longer caption")
            expect(spy.count).as("layouts need to hear about the re-fit").gte(1)
            H.expectSize(b, expectedWidth("A far longer caption"), nil)
        end)

        it("re-fits when the font size token grows", function()
            local b = H.C.Button({ label = "Apply" }, host)
            local before = b:GetWidth()
            H.T:CreateUserTheme("Big", "Modern")
            H.T:SetUserToken("Big", "fontSizeMd", 26)
            H.T:SetActive("Big")
            expect(b:GetWidth()).gt(before)
            H.expectSize(b, expectedWidth("Apply"), expectedHeight())
        end)

        it("re-fits when the spacing token grows", function()
            local b = H.C.Button({ label = "Apply" }, host)
            local before = b:GetWidth()
            H.T:CreateUserTheme("Roomy", "Modern")
            H.T:SetUserToken("Roomy", "spaceSm", 20)
            H.T:SetActive("Roomy")
            expect(b:GetWidth()).eq(before + 2 * (20 - 8))
        end)

        it("honours explicit padX and padY over the tokens", function()
            local b = H.C.Button({ label = "P", padX = 0, padY = 0 }, host)
            local size = H.token("fontSizeMd")
            H.expectSize(b, H.textWidth("P", size) + 2, H.lineHeight(size))
        end)

        it("handles an empty label without collapsing below its floors", function()
            local b = H.C.Button({ label = "" }, host)
            expect(b:GetWidth()).gt(0)
            expect(b:GetHeight()).gt(0)
        end)

        it("handles a missing label prop as empty text", function()
            local b = H.C.Button({}, host)
            expect(b:GetLabel()).eq("")
        end)
    end)

    describe("label placement", function()
        it("centres the label inside the button", function()
            local b = H.mount(H.C.Button({ label = "Centred" }, host))
            H.expectCenteredH(b._label, b:GetFrame())
            H.expectCenteredV(b._label, b:GetFrame())
        end)

        it("clamps the label to the inner box when a layout shrinks the button", function()
            local col = H.Layout:CreateContainer({ parent = host, layout = "flow",
                                                   dir = "vertical" })
            local b = H.C.Button({ label = "A very wide caption indeed" }, col:GetFrame())
            col:Add(b, { width = 60, height = 24 })
            local padX = H.token("spaceSm") + H.token("borderWidth")
            expect(b._label:GetWidth()).lte(60 - padX * 2 + 0.5)
            H.expectInside(b._label, b:GetFrame())
        end)

        it("never lets the label overflow the button", function()
            local col = H.Layout:CreateContainer({ parent = host, layout = "flow",
                                                   dir = "vertical" })
            local b = H.C.Button({ label = "Overflowing text content here" }, col:GetFrame())
            col:Add(b, { width = 200, height = 24 })
            for _, w in ipairs({ 200, 120, 40, 10, 300 }) do
                col:SetChildProps(b:GetFrame(), { width = w, height = 24 })
                H.expectInside(b._label, b:GetFrame())
            end
        end)

        it("measures the label off the shared probe, so repeated layouts do not shrink it", function()
            local col = H.Layout:CreateContainer({ parent = host, layout = "flow", dir = "vertical" })
            local b = H.C.Button({ label = "Stable caption" }, col:GetFrame())
            col:Add(b, { width = 80, height = 24 })
            local first = b._label:GetWidth()
            for _ = 1, 5 do col:Layout() end
            expect(b._label:GetWidth()).eq(first)
        end)
    end)

    describe("theming", function()
        it("uses colorBgAlt and colorBorder when idle", function()
            local b = H.C.Button({ label = "Idle" }, host)
            H.expectTokenColor(H.backdropColor(b), "colorBgAlt")
            H.expectTokenColor(H.borderColor(b), "colorBorder")
        end)

        it("tints border and label with the variant's intent token", function()
            for variant, token in pairs({ danger = "colorDanger", success = "colorSuccess",
                                          warning = "colorWarning" }) do
                local b = H.C.Button({ label = "V", variant = variant }, host)
                H.expectTokenColor(H.borderColor(b), token)
                local r, g, bl, a = b._label:GetTextColor()
                H.expectTokenColor({ r, g, bl, a }, token)
            end
        end)

        it("keeps a variant's background on the surface token", function()
            local b = H.C.Button({ label = "V", variant = "danger" }, host)
            H.expectTokenColor(H.backdropColor(b), "colorBgAlt")
        end)

        it("fades to the opacityDisabled token when disabled", function()
            local b = H.C.Button({ label = "V", variant = "danger" }, host)
            b:SetEnabled(false)
            local expected = H.token("opacityDisabled")
            expect(b:GetFrame():GetAlpha()).near(expected, 0.001)
            expect(b:GetFrame():IsMouseEnabled()).falsy()
            -- Variant border and label colour remain; only the fade carries the state.
            H.expectTokenColor(H.borderColor(b), "colorDanger")
            local r, g, bl, a = b._label:GetTextColor()
            H.expectTokenColor({ r, g, bl, a }, "colorDanger")
        end)

        it("highlights on hover and restores on leave", function()
            local b = H.C.Button({ label = "Hover" }, host)
            H.hover(b)
            H.expectTokenColor(H.backdropColor(b), "colorBgHover")
            H.expectTokenColor(H.borderColor(b), "colorBorderFocus")
            H.unhover(b)
            H.expectTokenColor(H.backdropColor(b), "colorBgAlt")
        end)

        it("uses the variant token for the hover border", function()
            local b = H.C.Button({ label = "Hover", variant = "success" }, host)
            H.hover(b)
            H.expectTokenColor(H.borderColor(b), "colorSuccess")
        end)

        it("deepens to colorAccentHover while pressed", function()
            local b = H.C.Button({ label = "Press" }, host)
            H.mouseDown(b)
            H.expectTokenColor(H.backdropColor(b), "colorBgPressed")
            H.expectTokenColor(H.borderColor(b), "colorAccentHover")
        end)

        it("ignores hover and press styling while disabled", function()
            local b = H.C.Button({ label = "Off" }, host)
            b:SetEnabled(false)
            local expected = H.token("opacityDisabled")
            expect(b:GetFrame():GetAlpha()).near(expected, 0.001)
            H.forceClick(b)
            -- Background remains on the resting surface token, not hover/pressed.
            H.expectTokenColor(H.backdropColor(b), "colorBgAlt")
        end)
    end)

    describe("interaction", function()
        it("calls onClick and emits CLICKED with the button name", function()
            local calls = 0
            local b = H.C.Button({ label = "Go", onClick = function() calls = calls + 1 end }, host)
            local spy = H.signalSpy(b, H.S.SIGNALS.CLICKED)
            H.click(b, "RightButton")
            expect(calls).eq(1)
            expect(spy.count).eq(1)
            expect(spy:arg(1)).eq("RightButton")
        end)

        it("stops receiving mouse input when disabled", function()
            local calls = 0
            local b = H.C.Button({ label = "Go", onClick = function() calls = calls + 1 end }, host)
            b:SetEnabled(false)
            expect(H.click(b)).as("a disabled button is not mouse-enabled").falsy()
            expect(calls).eq(0)
        end)

        it("guards internally too, in case the click reaches it anyway", function()
            local calls = 0
            local b = H.C.Button({ label = "Go", onClick = function() calls = calls + 1 end }, host)
            b:SetEnabled(false)
            H.forceClick(b)
            expect(calls).eq(0)
        end)

        it("emits MOUSE_ENTER and MOUSE_LEAVE", function()
            local b = H.C.Button({ label = "Go" }, host)
            local enter = H.signalSpy(b, H.S.SIGNALS.MOUSE_ENTER)
            local leave = H.signalSpy(b, H.S.SIGNALS.MOUSE_LEAVE)
            H.hover(b)
            H.unhover(b)
            expect(enter.count).eq(1)
            expect(leave.count).eq(1)
        end)

        it("emits ENABLED_CHANGED", function()
            local b = H.C.Button({ label = "Go" }, host)
            local spy = H.signalSpy(b, H.S.SIGNALS.ENABLED_CHANGED)
            b:SetEnabled(false)
            b:SetEnabled(true)
            expect(spy.count).eq(2)
            expect(spy:arg(1)).truthy()
        end)

        it("scales back to 1 after the press pop animation finishes", function()
            local b = H.C.Button({ label = "Pop" }, host)
            H.mouseDown(b)
            H.runAnimations()
            expect(b:GetFrame():GetScale()).near(1, 0.001)
        end)

        -- Chrome sized to fit a strip exactly cannot afford to grow on press: the pop
        -- pushes it outside its container and reads as the button jumping out and back.
        -- Ticking a fraction of animFast's first leg catches the pop mid-flight; asserting
        -- the settled scale would pass either way, since the pop returns to 1.
        it("pops on press by default", function()
            local b = H.C.Button({ label = "Pop" }, host)
            H.mouseDown(b)
            H.tick((H.token("animFast") or 0.12) * 0.25)
            expect(b:GetFrame():GetScale()).as("mid-pop scale").gt(1)
        end)

        it("does not pop when scalePop is false, but still shows pressed colours", function()
            local b = H.C.Button({ label = "Quiet", scalePop = false }, host)
            H.mouseDown(b)
            H.tick((H.token("animFast") or 0.12) * 0.25)
            expect(b:GetFrame():GetScale()).as("no pop queued").near(1, 0.001)
            -- Dropping the pop must not cost the press feedback entirely.
            H.expectTokenColor(H.backdropColor(b), "colorBgPressed")
            H.expectTokenColor(H.borderColor(b), "colorAccentHover")
        end)
    end)

    describe("lifecycle", function()
        it("hides and disconnects on Destroy", function()
            local b = H.C.Button({ label = "Bye" }, host)
            local spy = H.signalSpy(b, H.S.SIGNALS.CLICKED)
            b:Destroy()
            expect(b:IsShown()).falsy()
            expect(H.S:HasConnections(b, H.S.SIGNALS.CLICKED)).falsy()
            expect(spy.count).eq(0)
        end)

        it("stops restyling after Destroy", function()
            local b = H.C.Button({ label = "Bye" }, host)
            b:Destroy()
            expect(function() H.T:SetActive("Default") end).notThrows()
        end)
    end)
end)

