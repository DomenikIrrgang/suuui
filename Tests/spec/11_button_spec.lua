describe("Components.ColorSwatch", function()
    local host
    before_each(function()
        H.setup()
        host = H.parent(200, 200)
    end)

    it("sizes itself from the sizeControlMd token", function()
        local s = H.C.ColorSwatch({ value = { 1, 0, 0, 1 } }, host)
        local size = H.token("sizeControlMd")
        H.expectSize(s, size, size)
    end)

    it("tracks the size token when it changes", function()
        local s = H.C.ColorSwatch({ value = { 1, 0, 0, 1 } }, host)
        H.T:CreateUserTheme("Chunky", "Modern")
        H.T:SetUserToken("Chunky", "sizeControlMd", 40)
        H.T:SetActive("Chunky")
        H.expectSize(s, 40, 40)
    end)

    it("stops tracking the token once a size is given", function()
        local s = H.C.ColorSwatch({ value = { 1, 0, 0, 1 }, w = 30 }, host)
        H.T:CreateUserTheme("Chunky", "Modern")
        H.T:SetUserToken("Chunky", "sizeControlMd", 40)
        H.T:SetActive("Chunky")
        H.expectSize(s, 30, 30)
    end)

    it("uses a separate h when both are given", function()
        local s = H.C.ColorSwatch({ value = { 1, 0, 0, 1 }, w = 30, h = 12 }, host)
        H.expectSize(s, 30, 12)
    end)

    it("fills with the given colour, defaulting alpha to 1", function()
        local s = H.C.ColorSwatch({ value = { 0.25, 0.5, 0.75 } }, host)
        local r, g, b, a = s._swatch:GetColorTexture()
        expect({ r, g, b, a }).deepEq({ 0.25, 0.5, 0.75, 1 })
    end)

    it("defaults to opaque white with no value", function()
        local s = H.C.ColorSwatch({}, host)
        expect({ s:GetValue() }).deepEq({ 1, 1, 1, 1 })
    end)

    it("insets the colour by the border width inside a colorBorder frame", function()
        local s = H.mount(H.C.ColorSwatch({ value = { 1, 0, 0, 1 }, w = 20, h = 20 }, host))
        local bw = H.token("borderWidth")
        H.expectSize(s._border, 20, 20)
        H.expectSize(s._swatch, 20 - bw * 2, 20 - bw * 2)
        H.expectOffset(s._swatch, s:GetFrame(), bw, bw)
        local r, g, b, a = s._border:GetColorTexture()
        H.expectTokenColor({ r, g, b, a }, "colorBorder")
    end)

    it("returns the colour from GetValue", function()
        local s = H.C.ColorSwatch({ value = { 0.1, 0.2, 0.3, 0.4 } }, host)
        expect({ s:GetValue() }).deepEq({ 0.1, 0.2, 0.3, 0.4 })
    end)

    it("updates silently on SetValue", function()
        local s = H.C.ColorSwatch({ value = { 1, 1, 1, 1 } }, host)
        local spy = H.signalSpy(s, H.S.SIGNALS.VALUE_CHANGED)
        s:SetValue(0, 0.5, 1, 0.5)
        expect({ s:GetValue() }).deepEq({ 0, 0.5, 1, 0.5 })
        expect(spy.count).as("setters are deliberately silent").eq(0)
    end)

    it("defaults missing SetValue components to 1", function()
        local s = H.C.ColorSwatch({}, host)
        s:SetValue(nil, nil, nil, nil)
        expect({ s:GetValue() }).deepEq({ 1, 1, 1, 1 })
    end)

    it("formats the colour as uppercase hex, rounding to nearest", function()
        local s = H.C.ColorSwatch({ value = { 1, 0, 0.5, 1 } }, host)
        expect(s:GetHex()).eq("FF0080")
        s:SetValue(0, 0, 0, 1)
        expect(s:GetHex()).eq("000000")
        s:SetValue(1, 1, 1, 1)
        expect(s:GetHex()).eq("FFFFFF")
    end)

    it("emits CLICKED with the button", function()
        local s = H.C.ColorSwatch({}, host)
        local spy = H.signalSpy(s, H.S.SIGNALS.CLICKED)
        H.click(s, "RightButton")
        expect(spy:arg(1)).eq("RightButton")
    end)

    it("dims on hover and returns to full alpha on leave", function()
        local s = H.C.ColorSwatch({}, host)
        H.hover(s)
        expect(s:GetFrame():GetAlpha()).eq(0.8)
        H.unhover(s)
        expect(s:GetFrame():GetAlpha()).eq(1)
    end)

    it("dims to 0.4 while disabled and stays dim after hover", function()
        local s = H.C.ColorSwatch({}, host)
        s:SetEnabled(false)
        expect(s:GetFrame():GetAlpha()).eq(0.4)
        H.forceClick(s)
        H.unhover(s)
        expect(s:GetFrame():GetAlpha()).eq(0.4)
    end)

    it("ignores clicks while disabled", function()
        local s = H.C.ColorSwatch({}, host)
        local spy = H.signalSpy(s, H.S.SIGNALS.CLICKED)
        s:SetEnabled(false)
        H.forceClick(s)
        expect(spy.count).eq(0)
    end)

    it("emits SIZE_CHANGED once from an explicit resize", function()
        local s = H.C.ColorSwatch({}, host)
        local spy = H.signalSpy(s, H.S.SIGNALS.SIZE_CHANGED)
        s:SetSize(30, 30)
        expect(spy.count).eq(1)
    end)

    it("emits SIZE_CHANGED once when the size token changes", function()
        local s = H.C.ColorSwatch({}, host)
        local spy = H.signalSpy(s, H.S.SIGNALS.SIZE_CHANGED)
        H.T:CreateUserTheme("Chunky", "Modern")
        H.T:SetUserToken("Chunky", "sizeControlMd", 40)
        H.T:SetActive("Chunky")
        expect(spy.count).eq(1)
        expect(spy:arg(1)).eq(40)
    end)

    it("emits SIZE_CHANGED when a parent layout resizes it", function()
        local col = H.Layout:CreateContainer({ parent = host, layout = "flow", dir = "vertical" })
        local s = H.C.ColorSwatch({}, col:GetFrame())
        local spy = H.signalSpy(s, H.S.SIGNALS.SIZE_CHANGED)
        col:Add(s, { width = 50, height = 26 })
        expect(spy.count).gte(1)
        H.expectSize(s, 50, 26)
    end)
end)
