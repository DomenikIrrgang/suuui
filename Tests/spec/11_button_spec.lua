describe("Components.NavItem", function()
    local host
    before_each(function()
        H.setup()
        host = H.parent(300, 300)
    end)

    it("defaults to 160x32", function()
        local n = H.C.NavItem({ label = "General" }, host)
        H.expectSize(n, 160, 32)
    end)

    it("honours explicit dimensions", function()
        local n = H.C.NavItem({ label = "General", w = 200, h = 40 }, host)
        H.expectSize(n, 200, 40)
    end)

    it("insets the label by the spacing tokens and centres it vertically", function()
        local n = H.mount(H.C.NavItem({ label = "General", w = 160, h = 32 }, host))
        H.expectOffset(n._label, n:GetFrame(), H.token("spaceSm"), nil)
        H.expectCenteredV(n._label, n:GetFrame())
        H.expectSize(n._label, 160 - H.token("spaceSm") - H.token("spaceXs"), nil)
    end)

    it("left-justifies its label", function()
        local n = H.C.NavItem({ label = "General" }, host)
        expect(n._label:GetJustifyH()).eq("LEFT")
    end)

    it("autoW hugs the label instead of taking the nav default width", function()
        local n = H.mount(H.C.NavItem({ label = "Player", autoW = true }, host))
        expect(n:GetWidth()).as("hugs rather than inheriting 160").lt(160)
        expect(n:GetWidth()).as("still wide enough to read").gt(0)
    end)

    it("autoW reserves the render box, not the bare metric, for its label", function()
        -- The label is a STRETCHED stack child, so the insets the item adds are handed
        -- straight back to it and its box lands at exactly what _autosize measured. The
        -- client truncates with zero tolerance, so reserving the bare metric renders
        -- "Play..." for "Player" — which is what shipped in the settings tab strip.
        local n = H.mount(H.C.NavItem({ label = "Player", autoW = true }, host))
        local path, size = H.fontOf(n._label)
        local insets = H.token("spaceSm") + H.token("spaceXs")
        expect(n:GetWidth())
            .as("frame reserves the render box plus its insets")
            .gte(H.textBox("Player", size, path) + insets)
        expect(H.box(n._label).width)
            .as("label's own box clears the render box")
            .gte(H.textBox("Player", size, path))
        H.expectTextNotClipped(n._label)
    end)

    it("autoW re-reserves the render box after the label changes", function()
        local n = H.mount(H.C.NavItem({ label = "Player", autoW = true }, host))
        n:SetLabel("Focus Target")
        local path, size = H.fontOf(n._label)
        expect(H.box(n._label).width)
            .as("longer label still clears its render box")
            .gte(H.textBox("Focus Target", size, path))
        H.expectTextNotClipped(n._label)
    end)

    it("autoW re-reserves the render box when the font token grows", function()
        local n = H.mount(H.C.NavItem({ label = "Player", autoW = true }, host))
        H.T:CreateUserTheme("BigNav", "Modern")
        H.T:SetUserToken("BigNav", "fontSizeMd", 26)
        H.T:SetActive("BigNav")
        local path, size = H.fontOf(n._label)
        expect(H.box(n._label).width)
            .as("a bigger font token grows the reserved box")
            .gte(H.textBox("Player", size, path))
        H.expectTextNotClipped(n._label)
    end)

    it("starts unselected on the base surface with muted text", function()
        local n = H.C.NavItem({ label = "General" }, host)
        expect(n:IsSelected()).falsy()
        H.expectTokenColor(H.backdropColor(n), "colorBg")
        local r, g, b, a = n._label:GetTextColor()
        H.expectTokenColor({ r, g, b, a }, "colorTextMuted")
    end)

    it("starts selected when told to", function()
        local n = H.C.NavItem({ label = "General", selected = true }, host)
        expect(n:IsSelected()).truthy()
        H.expectTokenColor(H.backdropColor(n), "colorBgActive")
        local r, g, b, a = n._label:GetTextColor()
        H.expectTokenColor({ r, g, b, a }, "colorText")
    end)

    it("switches surface and text colour on SetSelected", function()
        local n = H.C.NavItem({ label = "General" }, host)
        n:SetSelected(true)
        H.expectTokenColor(H.backdropColor(n), "colorBgActive")
        n:SetSelected(false)
        H.expectTokenColor(H.backdropColor(n), "colorBg")
    end)

    it("does not emit VALUE_CHANGED from SetSelected", function()
        local n = H.C.NavItem({ label = "General" }, host)
        local spy = H.signalSpy(n, H.S.SIGNALS.VALUE_CHANGED)
        n:SetSelected(true)
        expect(spy.count).eq(0)
    end)

    it("shows a hover surface when unselected", function()
        local n = H.C.NavItem({ label = "General" }, host)
        H.hover(n)
        H.expectTokenColor(H.backdropColor(n), "colorBgHover")
        H.unhover(n)
        H.expectTokenColor(H.backdropColor(n), "colorBg")
    end)

    it("keeps the selected surface while hovered", function()
        local n = H.C.NavItem({ label = "General", selected = true }, host)
        H.hover(n)
        H.expectTokenColor(H.backdropColor(n), "colorBgActive")
    end)

    it("clears a stale hover state when selection changes", function()
        local n = H.C.NavItem({ label = "General" }, host)
        H.hover(n)
        n:SetSelected(true)
        n:SetSelected(false)
        H.expectTokenColor(H.backdropColor(n), "colorBg")
    end)

    it("emits CLICKED with the mouse button", function()
        local n = H.C.NavItem({ label = "General" }, host)
        local spy = H.signalSpy(n, H.S.SIGNALS.CLICKED)
        H.click(n)
        expect(spy:arg(1)).eq("LeftButton")
    end)

    it("ignores clicks and hover while disabled", function()
        local n = H.C.NavItem({ label = "General" }, host)
        local spy = H.signalSpy(n, H.S.SIGNALS.CLICKED)
        n:SetEnabled(false)
        H.forceClick(n)
        H.hover(n)
        expect(spy.count).eq(0)
    end)

    it("emits TEXT_CHANGED from SetLabel", function()
        local n = H.C.NavItem({ label = "A" }, host)
        local spy = H.signalSpy(n, H.S.SIGNALS.TEXT_CHANGED)
        n:SetLabel("B")
        expect(spy:arg(1)).eq("B")
        expect(n._label:GetText()).eq("B")
    end)

    it("re-measures the label when the font size token grows", function()
        local n = H.mount(H.C.NavItem({ label = "General", w = 160,
                                        h = H.controlHeight("sizeNavRow") }, host))
        local before = n._label:GetHeight()

        H.T:CreateUserTheme("Big", "Modern")
        H.T:SetUserToken("Big", "fontSizeMd", 22)
        H.T:SetActive("Big")

        local _, size = n._label:GetFont()
        expect(size).as("the label follows the font token").eq(22)
        expect(n._label:GetHeight()).as("a bigger font is a taller label").gt(before)
        H.expectSize(n._label, nil, H.lineHeight(22))
        H.expectTextNotClipped(n._label)
        H.expectCenteredV(n._label, n:GetFrame())
        H.expectInside(n._label, n:GetFrame())
    end)
end)

-- =============================================================================
-- Disabled-state coverage: every distinct visual state must differ from enabled.
-- The canonical mechanism is a root-frame alpha fade to the opacityDisabled token
-- plus mouse-off. No recolour, no desaturation — only the fade carries the state.
-- =============================================================================

describe("Button disabled state (canonical fade)", function()
    local host
    before_each(function()
        H.setup()
        host = H.parent(400, 200)
    end)

    it("fades the default variant when disabled", function()
        local b = H.C.Button({ label = "Go" }, host)
        b:SetEnabled(false)
        expect(b:GetFrame():GetAlpha()).near(H.token("opacityDisabled"), 0.001)
        expect(b:GetFrame():IsMouseEnabled()).falsy()
